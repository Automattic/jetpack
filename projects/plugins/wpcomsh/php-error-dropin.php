<?php
/**
 * Install and update the wp-content/php-error.php drop-in for wpcomsh.
 *
 * @package wpcomsh
 */

/**
 * A marker used to identify the php-error.php drop-in managed by wpcomsh.
 */
const WPCOMSH_PHP_ERROR_DROPIN_MARKER = 'Generated by WordPress.com Site Helper';

/**
 * Ensure the WordPress fatal-error template drop-in exists in wp-content.
 *
 * The drop-in is only created when missing, or updated when the existing file
 * is already managed by wpcomsh. Any third-party php-error.php file is left
 * untouched.
 *
 * @param string|null $source Optional. Path to the source template file.
 * @param string|null $target Optional. Path to the target drop-in file.
 * @return void
 */
function wpcomsh_maybe_install_php_error_dropin( $source = null, $target = null ) {
	if ( null === $source ) {
		$source = __DIR__ . '/php-error.php';
	}

	if ( null === $target ) {
		if ( ! defined( 'WP_CONTENT_DIR' ) ) {
			return;
		}

		$target = WP_CONTENT_DIR . '/php-error.php';
	}

	if ( ! is_readable( $source ) ) {
		return;
	}

	$source_contents = file_get_contents( $source ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
	if ( false === $source_contents ) {
		return;
	}

	if ( file_exists( $target ) ) {
		if ( ! is_readable( $target ) ) {
			return;
		}

		$target_contents = file_get_contents( $target ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		if ( false === $target_contents ) {
			return;
		}

		if ( $source_contents === $target_contents ) {
			return;
		}

		if ( ! str_contains( $target_contents, WPCOMSH_PHP_ERROR_DROPIN_MARKER ) ) {
			return;
		}
	}

	$temp_file = tempnam( dirname( $target ), 'wpcomsh-php-error-' );
	if ( false === $temp_file ) {
		return;
	}

	if ( false === file_put_contents( $temp_file, $source_contents ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
		unlink( $temp_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
		return;
	}

	if ( ! rename( $temp_file, $target ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.rename_rename
		unlink( $temp_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
	}
}
