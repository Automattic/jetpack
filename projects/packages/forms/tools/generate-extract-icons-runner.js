/**
 * Generates the extract-block-icons-runner.js file that imports all block icon.js
 * modules and extracts their markup at build time. Run before the extract-icons
 * webpack build so the runner has static imports for every block icon.
 *
 * No JSX in this file so it runs with plain Node.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname( fileURLToPath( import.meta.url ) );
const blocksDir = path.join( __dirname, '..', 'src', 'blocks' );

const blockDirs = fs.readdirSync( blocksDir ).filter( name => {
	const fullPath = path.join( blocksDir, name );
	return (
		fs.statSync( fullPath ).isDirectory() && fs.existsSync( path.join( fullPath, 'icon.jsx' ) )
	);
} );

const blockNames = blockDirs.map( dir => `jetpack/${ dir }` );
const imports = blockDirs
	.map( dir => {
		const varName = dir.replace( /-/g, '' ) + 'Icon';
		return `import ${ varName } from '../src/blocks/${ dir }/icon.jsx';`;
	} )
	.join( '\n' );

const moduleEntries = blockDirs
	.map( ( dir, i ) => {
		const varName = dir.replace( /-/g, '' ) + 'Icon';
		return `\t[ '${ blockNames[ i ] }', ${ varName } ]`;
	} )
	.join( ',\n' );

const runnerContent = `/**
 * GENERATED by tools/generate-extract-icons-runner.js — do not edit.
 * Extracts block icon markup at build time for use by Interactivity API (no React).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import * as React from '@wordpress/element';
import { Icon } from '@wordpress/components';
import ReactDOMServer from 'react-dom/server';

${ imports }

const __dirname = path.dirname( fileURLToPath( import.meta.url ) );

const MODULES = [
${ moduleEntries }
];

function getElementFromIcon( iconModule ) {
	// Bundled CJS may expose ESM default as .default or as the module itself
	const def = iconModule?.default ?? iconModule;
	if ( def === undefined || def === null ) {
		return null;
	}
	// { src: <element> } or { src: function }
	if ( def.src !== undefined ) {
		const src = def.src;
		if ( typeof src === 'function' ) {
			return src();
		}
		if ( React.isValidElement( src ) ) {
			return src;
		}
		// @wordpress/icons object (e.g. next) — wrap in Icon
		return React.createElement( Icon, { icon: src } );
	}
	// default is the component (e.g. form-step icon.js exports renderMaterialIcon() result)
	if ( typeof def === 'function' ) {
		return React.createElement( def );
	}
	return null;
}

const result = {};
for ( const [ blockName, iconModule ] of MODULES ) {
	try {
		const element = getElementFromIcon( iconModule );
		if ( element ) {
			if ( React.isValidElement( element ) ) {
				result[ blockName ] = ReactDOMServer.renderToStaticMarkup( element );
			} else {
				result[ blockName ] = ReactDOMServer.renderToStaticMarkup( element );
			}
		}
	} catch ( err ) {
		console.error( 'extract-icons:', blockName, err.message );
	}
}

const outPath = path.join( __dirname, '..', 'src', 'modules', 'block-icons.generated.json' );
fs.mkdirSync( path.dirname( outPath ), { recursive: true } );
fs.writeFileSync( outPath, JSON.stringify( result, null, '\\t' ) + '\\n' );

function escapePhpSingleQuoted( str ) {
	return str.replace( /\\\\/g, '\\\\\\\\' ).replace( /'/g, "\\\\'" );
}

const maxKeyLen = Math.max( ...Object.keys( result ).map( ( k ) => k.length ) );
const phpLines = [
	'<?php',
	'/**',
	' * GENERATED by tools/generate-extract-icons-runner.js — do not edit.',
	' * Block name => SVG markup for use in PHP (e.g. Interactivity API config).',
	' *',
	' * @package automattic/jetpack-forms',
	' */',
	'',
	'return array(',
	...Object.entries( result ).map( ( [ name, svg ] ) => {
		const key = "'" + name.replace( /'/g, "\\\\'" ) + "'";
		const padding = ' '.repeat( maxKeyLen - name.length );
		return \`\t\${ key }\${ padding } => '\${ escapePhpSingleQuoted( svg ) }',\`;
	} ),
	');',
	'',
].join( '\\n' );

const phpPath = path.join( __dirname, '..', 'src', 'contact-form', 'block-icons-generated.php' );
fs.mkdirSync( path.dirname( phpPath ), { recursive: true } );
fs.writeFileSync( phpPath, phpLines );
`;

const runnerPath = path.join( __dirname, 'extract-block-icons-runner.js' );
fs.writeFileSync( runnerPath, runnerContent );
