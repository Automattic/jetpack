/**
 * Library for the `emit-widget-strings` bin: one `_x()` per translatable
 * `widget.json` value, so gettext extraction sees the strings the widget
 * registry translates at hydration. Rationale and usage: README,
 * "widget.json strings".
 */

const fs = require( 'fs' );
const path = require( 'path' );

/**
 * Walk a metadata value in lockstep with its i18n schema, the way core's
 * `translate_settings_using_i18n_schema()` does, reporting every translatable
 * string with the context the schema assigns it.
 *
 * @param {*}        schema   - Schema node: a context string, a one-element
 *                            list, or a map of keys (`*` matching any key).
 * @param {*}        value    - The metadata node under that schema.
 * @param {Function} onString - Receives `( msgid, context )`.
 */
function walkSchema( schema, value, onString ) {
	if ( typeof schema === 'string' ) {
		if ( typeof value === 'string' && value !== '' ) {
			onString( value, schema );
		}
		return;
	}
	if ( Array.isArray( schema ) ) {
		if ( Array.isArray( value ) && schema.length > 0 ) {
			value.forEach( item => walkSchema( schema[ 0 ], item, onString ) );
		}
		return;
	}
	if (
		schema &&
		typeof schema === 'object' &&
		value &&
		typeof value === 'object' &&
		! Array.isArray( value )
	) {
		for ( const [ key, item ] of Object.entries( value ) ) {
			const sub = Object.hasOwn( schema, key ) ? schema[ key ] : schema[ '*' ];
			if ( sub !== undefined ) {
				walkSchema( sub, item, onString );
			}
		}
	}
}

/**
 * Collect the translatable strings of every `<widgetsDir>/<dir>/widget.json`.
 *
 * @param {string} widgetsDir - Directory holding one folder per widget.
 * @param {object} schema     - The widget i18n schema.
 * @param {string} domain     - Text domain for widgets that declare none.
 * @return {{ entries: Array<{ msgid: string, context: string, domain: string }>, widgets: number }} The unique (msgid, context, domain) triples in widget order, and the number of manifests read.
 */
function collectWidgetStrings( widgetsDir, schema, domain ) {
	const entries = [];
	const seen = new Set();
	let widgets = 0;
	const dirs = fs.existsSync( widgetsDir ) ? fs.readdirSync( widgetsDir ).sort() : [];

	for ( const dir of dirs ) {
		const file = path.join( widgetsDir, dir, 'widget.json' );
		if ( ! fs.existsSync( file ) ) {
			continue;
		}
		const widget = JSON.parse( fs.readFileSync( file, 'utf8' ) );
		widgets++;
		const textdomain =
			typeof widget.textdomain === 'string' && widget.textdomain !== ''
				? widget.textdomain
				: domain;

		for ( const [ field, fieldSchema ] of Object.entries( schema ) ) {
			walkSchema( fieldSchema, widget[ field ], ( msgid, context ) => {
				const key = JSON.stringify( [ msgid, context, textdomain ] );
				if ( ! seen.has( key ) ) {
					seen.add( key );
					entries.push( { msgid, context, domain: textdomain } );
				}
			} );
		}
	}

	return { entries, widgets };
}

/**
 * A PHP single-quoted string literal.
 *
 * @param {string} value - The string.
 * @return {string} The literal.
 */
function toPhpString( value ) {
	return `'${ value.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }'`;
}

/**
 * Render the stub file.
 *
 * @param {Array<{ msgid: string, context: string, domain: string }>} entries - The triples to emit.
 * @return {string} PHP source.
 */
function formatWidgetStringsPhp( entries ) {
	return [
		'<?php',
		'/**',
		' * Gettext reference stub for the widget.json metadata of the widgets in this',
		' * package: one call per translatable value, with the context the widget',
		' * registry looks up at hydration. Generated by emit-widget-strings; never loaded.',
		' */',
		'',
		...entries.map(
			( { msgid, context, domain } ) =>
				`_x( ${ toPhpString( msgid ) }, ${ toPhpString( context ) }, ${ toPhpString( domain ) } );`
		),
		'',
	].join( '\n' );
}

/**
 * Write the stub for a package, or remove a stale one when there is nothing to emit.
 *
 * @param {object} options            - Options.
 * @param {string} options.widgetsDir - Directory holding one folder per widget.
 * @param {object} options.schema     - The widget i18n schema.
 * @param {string} options.domain     - Text domain for widgets that declare none.
 * @param {string} options.outFile    - Path of the stub to write.
 * @return {{ entries: number, widgets: number, written: boolean }} What happened.
 */
function emitWidgetStrings( { widgetsDir, schema, domain, outFile } ) {
	const { entries, widgets } = collectWidgetStrings( widgetsDir, schema, domain );
	if ( entries.length === 0 ) {
		fs.rmSync( outFile, { force: true } );
		return { entries: 0, widgets, written: false };
	}
	fs.mkdirSync( path.dirname( outFile ), { recursive: true } );
	fs.writeFileSync( outFile, formatWidgetStringsPhp( entries ) );
	return { entries: entries.length, widgets, written: true };
}

module.exports = {
	walkSchema,
	collectWidgetStrings,
	formatWidgetStringsPhp,
	emitWidgetStrings,
};
