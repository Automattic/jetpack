/**
 * i18n stub generation for `strip-unminified-prod`.
 *
 * Background: GlotPress / `wp i18n make-pot` ignore `*.min.js` files, and
 * production builds delete the unminified siblings to keep mirrors small. If a
 * paired `.js` were simply deleted, nothing in the shipped plugin would carry
 * its translatable strings, so translate.wordpress.org would never generate
 * the md5(path)-keyed translation catalogs the runtime loader requests — and
 * the bundle would stay untranslated in production.
 *
 * `makeI18nStub(code)` extracts every gettext call from a bundle and returns a
 * tiny replacement source containing only those calls (plus any translator
 * comments), or `null` when the bundle has none. The stub keeps the original
 * file path, so extraction references and WordPress' path-hashed catalog file
 * names keep matching; it is never loaded at runtime because the generated
 * PHP loaders are pinned to the `.min.js` sibling by `strip-unminified-prod`.
 *
 * The callee matching is `@automattic/babel-plugin-replace-textdomain`'s own,
 * so the stub carries exactly the calls the stamp pass domained: bare
 * identifiers (`__(…)`), member expressions (`i18n.__(…)`), and esbuild's
 * sequence-expression interop shape (`(0, import_i18n.__)(…)`) — minus any
 * whose callee provably comes from somewhere other than `@wordpress/i18n`,
 * which would otherwise put a bundled dependency's `cache.__( key )` into the
 * .pot as a translatable string.
 */

const {
	defaultFunctions,
	defaultI18nModule,
	resolveGettextCallee,
} = require( '@automattic/babel-plugin-replace-textdomain' );
const { transformSync, types: t } = require( '@babel/core' );

/**
 * First line of every generated stub; used to recognise (and skip re-stubbing)
 * files that have already been processed.
 */
const STUB_HEADER = '// i18n reference stub generated by strip-unminified-prod.';

/**
 * Argument roles per gettext function, in positional order. Domain argument
 * positions match `@automattic/babel-plugin-replace-textdomain`'s defaults.
 *
 * - `string`: must be a string literal to be representable; a dynamic msgid
 * (index 0) or context makes the whole call unrepresentable and it is skipped,
 * since extraction tools could not have used it either.
 * - `count`: numeric plural-count argument, normalized to `1` in the stub.
 * - `domain`: text domain; emitted when it is a string literal, omitted otherwise.
 */
const GETTEXT_FUNCTIONS = {
	__: [ 'string', 'domain' ],
	_x: [ 'string', 'string', 'domain' ],
	_n: [ 'string', 'string', 'count', 'domain' ],
	_nx: [ 'string', 'string', 'count', 'string', 'domain' ],
};

const TRANSLATORS_RE = /translators\s*:/i;

/**
 * Return the string value of a node when it is representable as a literal in
 * the stub: a plain string literal, or a template literal with no expressions.
 *
 * @param {object} node - Babel AST node.
 * @return {string|null} The literal string value, or `null`.
 */
function literalString( node ) {
	if ( t.isStringLiteral( node ) ) {
		return node.value;
	}
	if ( t.isTemplateLiteral( node ) && node.expressions.length === 0 && node.quasis.length === 1 ) {
		return node.quasis[ 0 ].value.cooked;
	}
	return null;
}

/**
 * Resolve the gettext function name for a call, unwrapping the
 * `(0, obj.__)` sequence-expression shape esbuild emits for externalized
 * imports and checking that the callee traces back to `@wordpress/i18n`.
 * Returns `null` when the call is not a gettext call.
 *
 * @param {object} path - Babel path of the CallExpression / OptionalCallExpression.
 * @return {string|null} One of `__`/`_x`/`_n`/`_nx`, or `null`.
 */
function gettextFunctionName( path ) {
	const name = resolveGettextCallee( t, path, {
		functions: defaultFunctions,
		i18nModule: defaultI18nModule,
		requireI18nSource: true,
	} );
	return name && Object.hasOwn( GETTEXT_FUNCTIONS, name ) ? name : null;
}

/**
 * Render one gettext call as a stub line, or return `null` when the call is
 * not representable (dynamic msgid or context).
 *
 * @param {string}   fn   - Gettext function name.
 * @param {object[]} args - The call's argument nodes.
 * @return {string|null} A line like `__( "msg", "domain" );`, or `null`.
 */
function renderCall( fn, args ) {
	const roles = GETTEXT_FUNCTIONS[ fn ];
	const parts = [];
	for ( let i = 0; i < roles.length; i++ ) {
		const arg = args[ i ];
		if ( arg === undefined ) {
			break;
		}
		const role = roles[ i ];
		if ( role === 'count' ) {
			parts.push( '1' );
			continue;
		}
		const value = literalString( arg );
		if ( value === null ) {
			// A dynamic domain is droppable; a dynamic msgid/plural/context is not.
			if ( role === 'domain' ) {
				break;
			}
			return null;
		}
		parts.push( JSON.stringify( value ) );
	}
	if ( parts.length === 0 ) {
		return null;
	}
	return `${ fn }( ${ parts.join( ', ' ) } );`;
}

/**
 * Collect translator comments attached to the call or a few of its ancestors
 * (comments usually attach to the enclosing statement, not the call itself).
 *
 * @param {object} path - Babel path of the CallExpression.
 * @return {string[]} Comment texts (delimiters stripped, trimmed).
 */
function translatorComments( path ) {
	const seen = new Set();
	const comments = [];
	let node = path.node;
	let parent = path;
	for ( let depth = 0; node && depth < 5; depth++ ) {
		for ( const comment of node.leadingComments ?? [] ) {
			if ( TRANSLATORS_RE.test( comment.value ) && ! seen.has( comment.start ) ) {
				seen.add( comment.start );
				comments.push( comment.value.trim() );
			}
		}
		parent = parent.parentPath;
		node = parent?.node;
	}
	return comments;
}

/**
 * Extract every representable gettext call from a JS source.
 *
 * @param {string} code - JavaScript source (unminified bundle).
 * @return {{line: string, comments: string[]}[]} One entry per call, in source order.
 */
function extractGettextCalls( code ) {
	const calls = [];
	const collect = path => {
		const fn = gettextFunctionName( path );
		if ( ! fn ) {
			return;
		}
		const line = renderCall( fn, path.node.arguments );
		if ( line === null ) {
			return;
		}
		calls.push( { line, comments: translatorComments( path ) } );
	};
	// `a?.b?.__(…)` is an OptionalCallExpression with an OptionalMemberExpression
	// callee — a distinct node type the plain CallExpression visitor never sees.
	const collector = () => ( {
		visitor: {
			CallExpression: collect,
			OptionalCallExpression: collect,
		},
	} );
	transformSync( code, {
		babelrc: false,
		configFile: false,
		code: false,
		sourceType: 'unambiguous',
		plugins: [ collector ],
	} );
	return calls;
}

/**
 * Build the i18n stub for a bundle.
 *
 * @param {string} code - JavaScript source (unminified bundle).
 * @return {string|null} Stub source, or `null` when there are no gettext calls.
 */
function makeI18nStub( code ) {
	const calls = extractGettextCalls( code );
	if ( calls.length === 0 ) {
		return null;
	}

	const lines = [
		STUB_HEADER,
		'// Contains only the gettext calls from the original bundle so that string',
		'// extraction (translate.wordpress.org / `wp i18n make-pot`) keeps working after',
		'// the unminified bundle is dropped from production builds (GlotPress ignores',
		"// *.min.js). Same path as the original, so WordPress' md5(path)-keyed",
		'// translation files resolve. Never loaded at runtime: the generated PHP',
		'// loaders are pinned to the .min.js sibling.',
		'',
	];
	const seen = new Set();
	for ( const { line, comments } of calls ) {
		if ( seen.has( line ) ) {
			continue;
		}
		seen.add( line );
		for ( const comment of comments ) {
			lines.push( `/* ${ comment } */` );
		}
		lines.push( line );
	}
	return lines.join( '\n' ) + '\n';
}

/**
 * Whether a source string is a stub generated by this module.
 *
 * @param {string} code - File contents to check.
 * @return {boolean} `true` for generated stubs.
 */
function isStub( code ) {
	return code.startsWith( STUB_HEADER );
}

module.exports = { makeI18nStub, extractGettextCalls, isStub, STUB_HEADER };
