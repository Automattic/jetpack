<?php
/**
 * The Jetpack SEO wp-admin page shell.
 *
 * Registers the `admin.php?page=jetpack-seo` screen via Admin_Menu so it is
 * reachable on self-hosted, Atomic/WoA, and Simple sites alike, loads the
 * `@wordpress/build` (wp-build) dashboard bundle that renders it, and
 * bootstraps the React app's initial state onto the page.
 *
 * @package automattic/jetpack-seo-package
 */

namespace Automattic\Jetpack\SEO;

use Automattic\Jetpack\Admin_UI\Admin_Menu;
use Automattic\Jetpack\Connection\Manager as Connection_Manager;
use Automattic\Jetpack\Status;
use Automattic\Jetpack\Status\Host;
use Automattic\Jetpack\Terms_Of_Service;
use Automattic\Jetpack\Tracking;
use Automattic\Jetpack\WP_Build_Polyfills\WP_Build_Polyfills;

/**
 * Registers the SEO admin menu and loads the wp-build dashboard bundle.
 */
class Admin_Page {

	/**
	 * URL-facing menu slug (`admin.php?page=jetpack-seo`).
	 */
	const MENU_SLUG = 'jetpack-seo';

	/**
	 * Slug emitted by `@wordpress/build` (`wpPlugin.pages[0]`). wp-build's
	 * auto-generated enqueue callback only fires when `$screen->id` matches
	 * this value, so we alias the screen id to it via `current_screen` without
	 * changing the user-facing URL.
	 */
	const WP_BUILD_SLUG = 'jetpack-seo-dashboard';

	/**
	 * Render function generated by `@wordpress/build` into
	 * `build/pages/jetpack-seo-dashboard/page-wp-admin.php`. Naming convention:
	 * `{wpPlugin.name}_{page-with-underscores}_wp_admin_render_page`.
	 */
	const WP_BUILD_RENDER_FN = 'jetpack_seo_jetpack_seo_dashboard_wp_admin_render_page';

	/**
	 * Register the admin menu item.
	 *
	 * Uses Admin_Menu so the page is reachable on wp-admin across all site
	 * types. The render callback is wp-build's generated render function when
	 * the bundle is loaded (i.e. on the SEO page itself, after
	 * `maybe_load_wp_build()` ran at priority 1); otherwise it falls back to a
	 * bare mount node so the page never fatals on an unbuilt checkout.
	 *
	 * @return void
	 */
	public static function add_menu_item() {
		$callback = function_exists( self::WP_BUILD_RENDER_FN )
			? self::WP_BUILD_RENDER_FN
			: array( __CLASS__, 'render_fallback' );

		Admin_Menu::add_menu(
			'SEO',
			'SEO',
			'manage_options',
			self::MENU_SLUG,
			$callback,
			2
		);
	}

	/**
	 * On the SEO admin page, load the wp-build bundle, alias the screen id so
	 * wp-build enqueues its assets, and bootstrap the app's initial state.
	 *
	 * Hooked at `admin_menu` priority 1 so polyfills register and the render
	 * function is defined before `add_menu_item()` runs at priority 10.
	 *
	 * @return void
	 */
	public static function maybe_load_wp_build() {
		if ( ! self::is_seo_admin_request() ) {
			return;
		}

		self::load_wp_build();
		add_action( 'current_screen', array( __CLASS__, 'alias_screen_id_for_wp_build' ) );
		add_action( 'admin_enqueue_scripts', array( __CLASS__, 'enqueue_tracks_transport' ) );
		add_filter( 'jetpack_admin_js_script_data', array( __CLASS__, 'inject_script_data' ) );
	}

	/**
	 * Load the WordPress.com Tracks transport on the SEO admin page.
	 *
	 * `jetpack-analytics` (behind the client `recordSeoEvent()` wrapper) only queues
	 * events into `window._tkq`. Without `jp-tracks` (`stats.wp.com/w.js`) loaded
	 * nothing flushes that queue, so no event ever reaches Tracks and the queue just
	 * grows for the life of the page. Mirrors the Newsletter and Search dashboards.
	 *
	 * Registered from {@see self::maybe_load_wp_build()}, which already ran the
	 * SEO-admin-page check, so this only enqueues on our page. No-ops when the site
	 * hasn't opted into tracking (see {@see self::can_use_analytics()}) — the client
	 * wrapper keeps queueing into `_tkq`, but with no transport nothing is sent.
	 *
	 * @return void
	 */
	public static function enqueue_tracks_transport() {
		if ( ! self::can_use_analytics() ) {
			return;
		}

		wp_enqueue_script( 'jp-tracks', '//stats.wp.com/w.js', array(), gmdate( 'YW' ), true );
	}

	/**
	 * Whether this site has opted into the analytics Tracks depends on.
	 *
	 * Self-hosted Jetpack only sends Tracks once the site has agreed to the terms of
	 * service or connected a user, and never in offline mode — the same gate the host
	 * plugin applies in `Jetpack::initialize_tracking()`. The SEO dashboard is reachable
	 * before any of that is true, so it has to run the check itself rather than assume
	 * the host plugin already opened the door.
	 *
	 * The whole WordPress.com platform short-circuits — Simple *and* Atomic. Both are
	 * covered by WordPress.com's own terms, and neither is a reliable read for
	 * `should_enable_tracking()`: Simple has no Jetpack connection for it to inspect,
	 * and on Atomic it turns on a per-user connection that an admin may not have. Since
	 * paid Simple and Atomic sites *are* the population the launch metric counts, a
	 * false negative there would silently undercount the thing this instrumentation
	 * exists to measure. Self-hosted is the case the gate is actually for. Mirrors
	 * `Contact_Form_Plugin::can_use_analytics()`, widened from `IS_WPCOM` to the
	 * platform check.
	 *
	 * @return bool
	 */
	public static function can_use_analytics() {
		if ( ( new Host() )->is_wpcom_platform() ) {
			return true;
		}

		$tracking = new Tracking( 'jetpack', new Connection_Manager() );

		return $tracking->should_enable_tracking( new Terms_Of_Service(), new Status() );
	}

	/**
	 * Standard Tracks context for the SEO dashboard, per the Data team's unified
	 * properties standard. Bootstrapped onto the page so the client
	 * `recordSeoEvent()` wrapper attaches the same identifiers to every event.
	 *
	 * `blog_id` is the required join key for the distinct-site launch metric; it
	 * uses the WordPress.com-connected id where available so Simple, Atomic, and
	 * self-hosted rows join to the same site.
	 *
	 * @return array{blog_id:int, site_type:string, is_a11n:bool, is_test:bool, product_version:string}
	 */
	public static function get_tracks_context() {
		$host = new Host();
		if ( $host->is_wpcom_simple() ) {
			$site_type = 'simple';
		} elseif ( $host->is_atomic_platform() ) {
			$site_type = 'atomic';
		} else {
			$site_type = 'jetpack';
		}

		// `Jetpack_Options` ships in the jetpack-connection package's classmap, which
		// this package depends on transitively through jetpack-plans — so it's a real
		// dependency, not a host-plugin class needing a guard. Falls back to the local
		// blog id on a site that was never connected.
		$blog_id = (int) \Jetpack_Options::get_option( 'id' );
		if ( ! $blog_id ) {
			$blog_id = get_current_blog_id();
		}

		// Whether the visitor is an Automattician. `is_automattician()` is defined on
		// WordPress.com Simple only, so this reads false on Atomic and self-hosted even
		// for an a8c user. Known limitation, not a complete signal: the Atomic analogue
		// (`Status\Visitor::is_automattician_feature_flags_only()`) only detects proxied
		// requests, so it would report a different thing under the same property name.
		// Tracked with the rest of the Part 2 instrumentation on JETPACK-1728.
		$is_a11n = false;
		if ( function_exists( 'is_automattician' ) ) {
			// @phan-suppress-next-line PhanUndeclaredFunction -- is_automattician() lives on WordPress.com, guarded by function_exists.
			$is_a11n = (bool) is_automattician();
		}

		// Internal traffic to exclude from the metrics: WordPress.com staging sites,
		// installs declaring a non-production environment, and local installs.
		// `Status::is_staging_site()` covers the middle case but is deprecated since
		// 3.3.0, and its suggested replacement (`in_safe_mode`) detects an Identity
		// Crisis rather than a staging site.
		$is_test = (bool) get_option( 'wpcom_is_staging_site' )
			|| 'production' !== wp_get_environment_type()
			|| ( new Status() )->is_local_site();

		return array(
			'blog_id'         => $blog_id,
			'site_type'       => $site_type,
			'is_a11n'         => $is_a11n,
			'is_test'         => $is_test,
			'product_version' => Initializer::PACKAGE_VERSION,
		);
	}

	/**
	 * Load wp-build's generated registration file and register the polyfills
	 * the bundle depends on. No-op on a fresh checkout before `pnpm build`, in
	 * which case `add_menu_item()` falls back to {@see self::render_fallback()}.
	 *
	 * @return void
	 */
	private static function load_wp_build() {
		$build_index = dirname( __DIR__ ) . '/build/build.php';

		if ( ! file_exists( $build_index ) ) {
			return;
		}

		require_once $build_index;

		WP_Build_Polyfills::register(
			'jetpack-seo',
			array_merge( WP_Build_Polyfills::SCRIPT_HANDLES, WP_Build_Polyfills::MODULE_IDS )
		);
	}

	/**
	 * Alias the current screen id to wp-build's expected slug so its
	 * auto-generated enqueue callback fires for our user-facing page.
	 *
	 * @param \WP_Screen|null $screen The current screen object (passed by WP).
	 * @return void
	 */
	public static function alias_screen_id_for_wp_build( $screen ) {
		if ( ! is_object( $screen ) ) {
			return;
		}

		$screen->id = self::WP_BUILD_SLUG;
	}

	/**
	 * Bootstrap the React app's initial state onto `window.JetpackScriptData.seo`.
	 *
	 * Because wp-build pages load as ES modules, `wp_localize_script` can't
	 * attach data to them; the shared `jetpack_admin_js_script_data` filter
	 * (printed by the Script_Data package onto the `jetpack-script-data` handle
	 * the bundle already depends on) is the supported channel. The per-tab state
	 * is provided as an apiFetch *preload* (mirrors Podcast) so the app resolves
	 * it with no request on a normal load yet can re-fetch when the preload is
	 * missing or stale, rather than dead-ending on a one-shot read.
	 *
	 * @param array $data Script data being injected onto the page.
	 * @return array
	 */
	public static function inject_script_data( $data ) {
		if ( ! is_array( $data ) ) {
			$data = array();
		}

		// Preload the dashboard's REST reads into the page so the app resolves them from
		// cache on first paint with no network request — while still being able to
		// re-fetch if that preload is ever missing or stale. This replaces injecting the
		// raw payloads, which the app read synchronously once and couldn't recover from
		// when momentarily absent (the load-error dead-end). See Dashboard_Data::register_rest_reads()
		// and the client readers `_inc/data/get-preloaded.ts` + `_inc/data/use-ensure-tab-data.ts`.
		$data[ Initializer::SCRIPT_DATA_KEY ]['preload'] = array_reduce(
			Dashboard_Data::rest_read_paths(),
			'rest_preload_api_request',
			array()
		);

		// Small synchronous reads used outside the per-tab data stores, and not part of
		// the load-error path.
		$data[ Initializer::SCRIPT_DATA_KEY ]['google_verify'] = Dashboard_Data::get_google_verify_data();
		$data[ Initializer::SCRIPT_DATA_KEY ]['site']          = Dashboard_Data::get_site_data();

		// Plan-gating signal for below-Premium WordPress.com sites: when gated, the
		// dashboard reduces to a free subset and surfaces the upsell banner. Self-hosted
		// is never gated (see Initializer::is_gated()). The upsell URL is only meaningful
		// when gated, so it's built only then — every ungated and self-hosted admin load
		// otherwise pays for a site-suffix lookup it never uses.
		$is_gated                                       = Initializer::is_gated();
		$data[ Initializer::SCRIPT_DATA_KEY ]['gating'] = array(
			'is_gated'   => $is_gated,
			'upsell_url' => $is_gated ? Initializer::get_upsell_url() : '',
		);

		// Standard Tracks identifiers, attached to every SEO event by the client
		// `recordSeoEvent()` wrapper (see `_inc/data/record-seo-event.ts`).
		$data[ Initializer::SCRIPT_DATA_KEY ]['tracks'] = self::get_tracks_context();

		return $data;
	}

	/**
	 * Fallback render used when the wp-build artifact is missing (unbuilt
	 * checkout). Renders a bare wrapper so the page loads without the app.
	 *
	 * @return void
	 */
	public static function render_fallback() {
		echo '<div class="wrap"><h1>SEO</h1></div>';
	}

	/**
	 * Whether the current request targets the SEO admin page.
	 *
	 * @return bool
	 */
	private static function is_seo_admin_request() {
		// phpcs:ignore WordPress.Security.NonceVerification.Recommended
		if ( ! is_admin() || ! isset( $_GET['page'] ) ) {
			return false;
		}

		// phpcs:ignore WordPress.Security.NonceVerification.Recommended
		return self::MENU_SLUG === sanitize_text_field( wp_unslash( $_GET['page'] ) );
	}
}
