#!/usr/bin/env node
/**
 * Regenerates `_inc/assets/inline-svgs.ts` from the SVG sources.
 *
 * The generated module is checked in: `typecheck` and `jest` resolve imports
 * without running either build chain, so a build-time-only artifact would
 * break both.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.join( import.meta.dirname, '..' );

// exportName → path relative to `_inc/`.
const SVGS = {
	a4aBannerIcon: 'components/a4a-banner/icon.svg',
	connectionScreenApple: 'components/connection-screen/apple.svg',
	connectionScreenGithub: 'components/connection-screen/github.svg',
	connectionScreenGoogle: 'components/connection-screen/google.svg',
	connectionScreenWordpress: 'components/connection-screen/wordpress.svg',
	connectionStatusCloud: 'components/connection-status-card/cloud.svg',
	connectionStatusEmptyAvatar: 'components/connection-status-card/empty-avatar.svg',
	connectionStatusJetpackGray: 'components/connection-status-card/jetpack-gray.svg',
	connectionStatusJetpack: 'components/connection-status-card/jetpack.svg',
	protectCardShieldInactive:
		'components/product-cards-section/protect-card/assets/shield-inactive.svg',
	protectCardShieldOff: 'components/product-cards-section/protect-card/assets/shield-off.svg',
	protectCardShieldPartial:
		'components/product-cards-section/protect-card/assets/shield-partial.svg',
	protectCardShieldSuccess:
		'components/product-cards-section/protect-card/assets/shield-success.svg',
	productInterstitialAntispamLogo: 'components/product-interstitial/logos/antispam-logo.svg',
};

const entries = await Promise.all(
	Object.entries( SVGS ).map( async ( [ name, relative ] ) => {
		const svg = await readFile( path.join( ROOT, '_inc', relative ) );
		return `export const ${ name } =\n\t'data:image/svg+xml;base64,${ svg.toString( 'base64' ) }';`;
	} )
);

const header = `// Generated by \`pnpm run generate:inline-svgs\`. Do not edit.
// wp-build's esbuild pipeline has no image loader, so SVGs reachable from the
// route are inlined here instead of imported. See bin/generate-inline-svgs.mjs.
`;

await writeFile(
	path.join( ROOT, '_inc/assets/inline-svgs.ts' ),
	`${ header }\n${ entries.join( '\n\n' ) }\n`
);
