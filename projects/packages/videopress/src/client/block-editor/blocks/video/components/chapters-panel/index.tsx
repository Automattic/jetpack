/**
 * External dependencies
 */
import { Button, Notice, PanelBody } from '@wordpress/components';
import { store as coreStore } from '@wordpress/core-data';
import { useDispatch } from '@wordpress/data';
import { useCallback, useMemo, useState } from '@wordpress/element';
import { __ } from '@wordpress/i18n';
/**
 * Internal dependencies
 */
import ChapterManagerModal from '../../../../../components/chapter-manager-modal/lazy';
import { getVideoPressUrl } from '../../../../../lib/url';
import {
	chapterStartAtToSeconds,
	formatChapterTime,
} from '../../../../../utils/video-chapters/chapter-time';
import extractVideoChapters from '../../../../../utils/video-chapters/extract-video-chapters';
import './styles.scss';
/**
 * Types
 */
import type { VideoTextTrack } from '../../../../../lib/video-tracks/types';
import type { ChaptersPanelProps } from '../../types';
import type { ReactElement } from 'react';

/**
 * Inspector panel surfacing the video's chapters: a read-only list parsed
 * from the description, and the entry point to the chapter manager modal.
 *
 * @param props                        - Component props.
 * @param props.attributes             - Block attributes.
 * @param props.setAttributes          - Block attributes setter.
 * @param props.isAutoGeneratedChapter - Whether an existing chapters track is auto-generated.
 * @param props.isRequestingVideoData  - Whether video data is still loading.
 * @param props.videoBelongToSite      - Whether the video can be edited from this site.
 * @return The chapters panel.
 */
export default function ChaptersPanel( {
	attributes,
	setAttributes,
	isAutoGeneratedChapter,
	isRequestingVideoData,
	videoBelongToSite,
}: ChaptersPanelProps ): ReactElement {
	const { guid, title, description = '', poster, isPrivate, duration, tracks = [] } = attributes;
	const [ isModalOpen, setIsModalOpen ] = useState( false );
	const invalidateResolution = useDispatch( coreStore ).invalidateResolution;

	const chapters = useMemo( () => extractVideoChapters( description ), [ description ] );
	const uploadedChaptersTrack = tracks.find( track => track.kind === 'chapters' );
	const hasManualChaptersFile = !! uploadedChaptersTrack && ! isAutoGeneratedChapter;

	const onSaved = useCallback(
		( nextDescription: string, updatedTracks: VideoTextTrack[] ) => {
			/*
			 * The block attribute serializes into post markup, so persist only the
			 * historical `{ src, kind, srcLang, label }` shape rather than the
			 * modal's full track objects with processing state.
			 */
			setAttributes( {
				description: nextDescription,
				tracks: updatedTracks.map( ( { src, kind, srcLang, label } ) => ( {
					src,
					kind,
					srcLang,
					label,
				} ) ),
			} );
			invalidateResolution( 'getEmbedPreview', [ getVideoPressUrl( guid, attributes ) ] );
		},
		[ attributes, guid, invalidateResolution, setAttributes ]
	);

	return (
		<PanelBody title={ __( 'Chapters', 'jetpack-videopress-pkg' ) }>
			{ chapters.length ? (
				<ul className="videopress-chapters-panel__list">
					{ chapters.map( chapter => (
						<li key={ `${ chapter.startAt }-${ chapter.title }` }>
							<span className="videopress-chapters-panel__time">
								{ formatChapterTime( chapterStartAtToSeconds( chapter.startAt ) ) }
							</span>
							<span className="videopress-chapters-panel__title">{ chapter.title }</span>
						</li>
					) ) }
				</ul>
			) : (
				<p className="videopress-chapters-panel__empty">
					{ __(
						'Chapters help viewers navigate long videos. Add timestamps and titles to create them.',
						'jetpack-videopress-pkg'
					) }
				</p>
			) }

			{ hasManualChaptersFile && (
				<Notice status="info" isDismissible={ false }>
					{ __(
						'This video’s chapters come from an uploaded VTT file. Managing chapters here will replace it.',
						'jetpack-videopress-pkg'
					) }
				</Notice>
			) }

			<Button
				variant="secondary"
				className="videopress-chapters-panel__manage"
				disabled={ ! guid || isRequestingVideoData || ! videoBelongToSite }
				onClick={ () => setIsModalOpen( true ) }
			>
				{ __( 'Manage chapters', 'jetpack-videopress-pkg' ) }
			</Button>

			{ !! guid && isModalOpen && (
				<ChapterManagerModal
					isOpen={ isModalOpen }
					guid={ guid }
					title={ title }
					description={ description }
					poster={ poster }
					isPrivate={ isPrivate }
					tracks={ tracks }
					durationMs={ duration }
					onClose={ () => setIsModalOpen( false ) }
					onSaved={ onSaved }
				/>
			) }
		</PanelBody>
	);
}
