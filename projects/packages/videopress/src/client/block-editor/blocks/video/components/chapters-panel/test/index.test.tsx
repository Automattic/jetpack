import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import ChaptersPanel from '..';

const mockInvalidateResolution = jest.fn();
let lastModalProps: Record< string, unknown > | null = null;

jest.mock( '@wordpress/components', () => ( {
	Button: ( { children, onClick, disabled } ) => (
		<button onClick={ onClick } disabled={ disabled }>
			{ children }
		</button>
	),
	Notice: ( { children } ) => <div role="alert">{ children }</div>,
	PanelBody: ( { title, children } ) => (
		<section>
			<h2>{ title }</h2>
			{ children }
		</section>
	),
} ) );

jest.mock( '@wordpress/core-data', () => ( {
	store: 'core',
} ) );

jest.mock( '@wordpress/data', () => ( {
	useDispatch: () => ( { invalidateResolution: mockInvalidateResolution } ),
} ) );

jest.mock( '@wordpress/i18n', () => ( {
	__: ( text: string ) => text,
} ) );

jest.mock( '../../../../../../components/chapter-manager-modal/lazy', () => ( {
	__esModule: true,
	default: ( props: Record< string, unknown > ) => {
		lastModalProps = props;
		return <div data-testid="chapter-manager-modal" />;
	},
} ) );

jest.mock( '../../../../../../lib/url', () => ( {
	getVideoPressUrl: jest.fn( () => 'https://videopress.com/v/test-guid' ),
} ) );

const attributes = {
	guid: 'test-guid',
	title: 'Test video',
	description: '00:00 Intro\n00:30 Middle\n01:00 End',
	tracks: [],
};

const renderPanel = ( overrides: Record< string, unknown > = {} ) => {
	const setAttributes = jest.fn();
	render(
		<ChaptersPanel
			attributes={ { ...attributes, ...( overrides.attributes as object ) } }
			setAttributes={ setAttributes }
			isAutoGeneratedChapter
			isRequestingVideoData={ false }
			videoBelongToSite
			{ ...overrides }
		/>
	);
	return { setAttributes };
};

beforeEach( () => {
	jest.clearAllMocks();
	lastModalProps = null;
} );

describe( 'ChaptersPanel', () => {
	it( 'lists chapters parsed from the description', () => {
		renderPanel();
		expect( screen.getByText( 'Intro' ) ).toBeInTheDocument();
		expect( screen.getByText( '00:30' ) ).toBeInTheDocument();
		expect( screen.getByText( 'End' ) ).toBeInTheDocument();
	} );

	it( 'shows an empty state when the description has no chapters', () => {
		renderPanel( { attributes: { ...attributes, description: 'Just prose.' } } );
		expect(
			screen.getByText(
				'Chapters help viewers navigate long videos. Add timestamps and titles to create them.'
			)
		).toBeInTheDocument();
	} );

	it( 'opens the chapter manager modal', async () => {
		renderPanel();
		expect( lastModalProps ).toBeNull();
		await userEvent.click( screen.getByRole( 'button', { name: 'Manage chapters' } ) );
		expect( screen.getByTestId( 'chapter-manager-modal' ) ).toBeInTheDocument();
		expect( lastModalProps ).toMatchObject( { guid: 'test-guid', isOpen: true } );
	} );

	it( 'persists the rewritten description and tracks on save', async () => {
		const { setAttributes } = renderPanel();
		await userEvent.click( screen.getByRole( 'button', { name: 'Manage chapters' } ) );

		const onSaved = lastModalProps?.onSaved as (
			description: string,
			tracks: Array< Record< string, string > >
		) => void;
		onSaved( '00:00 New intro', [
			{
				kind: 'chapters',
				srcLang: 'en',
				label: 'English (auto-generated)',
				src: 'chapters.vtt',
				extra: 'dropped',
			},
		] );

		expect( setAttributes ).toHaveBeenCalledWith( {
			description: '00:00 New intro',
			tracks: [
				{
					kind: 'chapters',
					srcLang: 'en',
					label: 'English (auto-generated)',
					src: 'chapters.vtt',
				},
			],
		} );
		expect( mockInvalidateResolution ).toHaveBeenCalledWith( 'getEmbedPreview', [
			'https://videopress.com/v/test-guid',
		] );
	} );

	it( 'disables the manage button without a guid', () => {
		renderPanel( { attributes: { ...attributes, guid: undefined } } );
		expect( screen.getByRole( 'button', { name: 'Manage chapters' } ) ).toBeDisabled();
	} );

	it( 'notes when chapters come from a manually uploaded file', () => {
		renderPanel( {
			attributes: {
				...attributes,
				tracks: [ { kind: 'chapters', srcLang: 'en', label: 'Chapters', src: 'manual.vtt' } ],
			},
			isAutoGeneratedChapter: false,
		} );
		expect( screen.getByRole( 'alert' ) ).toBeInTheDocument();
	} );
} );
