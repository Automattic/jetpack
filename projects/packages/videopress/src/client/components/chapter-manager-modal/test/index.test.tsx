import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import ChapterManagerModal from '..';
import {
	deleteTrackForGuid,
	isAutogeneratedChapterFile,
	uploadTrackForGuid,
} from '../../../lib/video-tracks';

jest.mock( '@wordpress/components', () => ( {
	Button: jest
		.requireActual( '@wordpress/element' )
		.forwardRef( ( { children, onClick, disabled, label }, ref ) => (
			<button ref={ ref } aria-label={ label } onClick={ onClick } disabled={ disabled }>
				{ children ?? label }
			</button>
		) ),
	Modal: ( { children, title, onRequestClose } ) => (
		<div role="dialog" aria-label={ title }>
			<button aria-label="Close dialog" onClick={ onRequestClose }>
				Close dialog
			</button>
			{ children }
		</div>
	),
	Notice: ( { children } ) => <div role="alert">{ children }</div>,
	TextControl: ( { disabled, label, onBlur, onChange, onKeyDown, value } ) => (
		<div>
			<input
				aria-label={ label }
				disabled={ disabled }
				value={ value }
				onChange={ event => onChange( event.target.value ) }
				onBlur={ onBlur }
				onKeyDown={ onKeyDown }
			/>
		</div>
	),
} ) );

jest.mock( '@wordpress/i18n', () => ( {
	__: ( text: string ) => text,
	isRTL: () => false,
	sprintf: ( text: string, ...args: Array< number | string > ) => {
		let sequentialIndex = 0;
		return text.replace( /%(\d+\$)?[sd]/g, ( _match, position: string | undefined ) => {
			const index = position ? Number( position.replace( '$', '' ) ) - 1 : sequentialIndex++;
			return String( args[ index ] );
		} );
	},
} ) );

jest.mock( '@wordpress/icons', () => ( {
	close: 'close',
	closeSmall: 'close-small',
	plus: 'plus',
	video: 'video',
} ) );

jest.mock( 'debug', () => () => jest.fn() );

jest.mock( '../../../lib/fetch-video-item', () => ( {
	fetchVideoItem: jest.fn( () => Promise.resolve( { width: 1920, height: 1080 } ) ),
} ) );

jest.mock( '../../../lib/video-tracks', () => ( {
	deleteTrackForGuid: jest.fn(),
	flattenVideoTracks: jest.fn( () => [] ),
	isAutogeneratedChapterFile: jest.fn(),
	normalizeVideoTextTrackResponse: jest.fn( ( response, fallback ) => ( {
		...fallback,
		src: typeof response === 'object' && response !== null ? response.src : '',
	} ) ),
	uploadTrackForGuid: jest.fn(),
} ) );

jest.mock( '../../caption-manager-modal/caption-preview-player', () => {
	const { forwardRef, useImperativeHandle } = jest.requireActual( '@wordpress/element' );
	return {
		__esModule: true,
		default: forwardRef( ( props, ref ) => {
			useImperativeHandle( ref, () => ( {
				getCurrentTime: () => 42,
				seekTo: jest.fn(),
				seekBy: jest.fn(),
				togglePlayback: jest.fn(),
				pauseWhileTypingNow: jest.fn(),
			} ) );
			return <div data-testid="preview-player" />;
		} ),
	};
} );

const mockUploadTrackForGuid = uploadTrackForGuid as jest.MockedFunction<
	typeof uploadTrackForGuid
>;
const mockDeleteTrackForGuid = deleteTrackForGuid as jest.MockedFunction<
	typeof deleteTrackForGuid
>;
const mockIsAutogeneratedChapterFile = isAutogeneratedChapterFile as jest.MockedFunction<
	typeof isAutogeneratedChapterFile
>;

const DESCRIPTION = 'Intro prose.\n00:00 Intro\n00:30 Middle\n01:00 End';

const CHAPTERS_TRACK = {
	kind: 'chapters' as const,
	srcLang: 'en',
	label: 'English (auto-generated)',
	src: 'chapters.vtt',
};

const renderModal = ( props: Record< string, unknown > = {} ) => {
	const onClose = jest.fn();
	const onSaved = jest.fn();
	render(
		<ChapterManagerModal
			isOpen
			guid="test-guid"
			title="Test video"
			description={ DESCRIPTION }
			onClose={ onClose }
			onSaved={ onSaved }
			{ ...props }
		/>
	);
	return { onClose, onSaved };
};

beforeEach( () => {
	jest.clearAllMocks();
	mockIsAutogeneratedChapterFile.mockResolvedValue( true );
	mockUploadTrackForGuid.mockResolvedValue( { src: 'chapters.vtt' } );
	mockDeleteTrackForGuid.mockResolvedValue( {} );
} );

describe( 'ChapterManagerModal', () => {
	it( 'renders a row per chapter parsed from the description', () => {
		renderModal();
		const timeInputs = screen.getAllByLabelText( 'Start time' );
		expect( timeInputs.map( input => ( input as HTMLInputElement ).value ) ).toEqual( [
			'00:00',
			'00:30',
			'01:00',
		] );
		const titleInputs = screen.getAllByLabelText( 'Title' );
		expect( titleInputs.map( input => ( input as HTMLInputElement ).value ) ).toEqual( [
			'Intro',
			'Middle',
			'End',
		] );
	} );

	it( 'disables Save while pristine and enables it after an edit', async () => {
		renderModal();
		const saveButton = screen.getByRole( 'button', { name: 'Save chapters' } );
		expect( saveButton ).toBeDisabled();

		await userEvent.type( screen.getAllByLabelText( 'Title' )[ 0 ], '!' );
		expect( saveButton ).toBeEnabled();
	} );

	it( 'blocks saving fewer than three chapters and explains why', async () => {
		renderModal();
		await userEvent.click( screen.getAllByLabelText( 'Remove chapter' )[ 2 ] );
		expect( screen.getByText( 'Add at least 3 chapters.' ) ).toBeInTheDocument();
		expect( screen.getByRole( 'button', { name: 'Save chapters' } ) ).toBeDisabled();
	} );

	it( 'uploads the chapters track on save and reports the new description', async () => {
		const { onClose, onSaved } = renderModal();
		await userEvent.type( screen.getAllByLabelText( 'Title' )[ 0 ], '!' );
		await userEvent.click( screen.getByRole( 'button', { name: 'Save chapters' } ) );

		await waitFor( () => expect( onSaved ).toHaveBeenCalled() );

		expect( mockUploadTrackForGuid ).toHaveBeenCalledWith(
			expect.objectContaining( {
				kind: 'chapters',
				srcLang: 'en',
				label: 'English (auto-generated)',
				tmpFile: expect.any( File ),
			} ),
			'test-guid'
		);
		const [ nextDescription, updatedTracks ] = onSaved.mock.calls[ 0 ];
		expect( nextDescription ).toContain( '00:00 Intro!' );
		expect( nextDescription ).toContain( 'Intro prose.' );
		expect( updatedTracks ).toEqual(
			expect.arrayContaining( [ expect.objectContaining( { kind: 'chapters', srcLang: 'en' } ) ] )
		);
		expect( onClose ).toHaveBeenCalled();
	} );

	it( 'deletes the chapters track when all rows are removed', async () => {
		const { onSaved } = renderModal( { tracks: [ CHAPTERS_TRACK ] } );
		for ( let i = 0; i < 3; i++ ) {
			await userEvent.click( screen.getAllByLabelText( 'Remove chapter' )[ 0 ] );
		}
		await userEvent.click( screen.getByRole( 'button', { name: 'Save chapters' } ) );

		await waitFor( () => expect( onSaved ).toHaveBeenCalled() );

		expect( mockDeleteTrackForGuid ).toHaveBeenCalledWith(
			{ kind: 'chapters', srcLang: 'en' },
			'test-guid'
		);
		expect( mockUploadTrackForGuid ).not.toHaveBeenCalled();
		const [ nextDescription, updatedTracks ] = onSaved.mock.calls[ 0 ];
		expect( nextDescription ).toBe( 'Intro prose.' );
		expect( updatedTracks ).toEqual( [] );
	} );

	it( 'asks before replacing a manually uploaded chapters track', async () => {
		mockIsAutogeneratedChapterFile.mockResolvedValue( false );
		const { onSaved } = renderModal( { tracks: [ CHAPTERS_TRACK ] } );

		await waitFor( () => expect( mockIsAutogeneratedChapterFile ).toHaveBeenCalled() );
		await userEvent.type( screen.getAllByLabelText( 'Title' )[ 0 ], '!' );
		await userEvent.click( screen.getByRole( 'button', { name: 'Save chapters' } ) );

		expect( mockUploadTrackForGuid ).not.toHaveBeenCalled();
		expect(
			screen.getByText(
				'This video’s chapters file may have been uploaded manually. Saving will replace it.'
			)
		).toBeInTheDocument();

		await userEvent.click( screen.getByRole( 'button', { name: 'Replace' } ) );
		await waitFor( () => expect( onSaved ).toHaveBeenCalled() );
		expect( mockUploadTrackForGuid ).toHaveBeenCalled();
	} );

	it( 'cancelling the replace confirmation does not upload', async () => {
		mockIsAutogeneratedChapterFile.mockResolvedValue( false );
		const { onSaved } = renderModal( { tracks: [ CHAPTERS_TRACK ] } );

		await waitFor( () => expect( mockIsAutogeneratedChapterFile ).toHaveBeenCalled() );
		await userEvent.type( screen.getAllByLabelText( 'Title' )[ 0 ], '!' );
		await userEvent.click( screen.getByRole( 'button', { name: 'Save chapters' } ) );
		await userEvent.click( screen.getByRole( 'button', { name: 'Cancel' } ) );

		expect( mockUploadTrackForGuid ).not.toHaveBeenCalled();
		expect( onSaved ).not.toHaveBeenCalled();
		expect( screen.getByRole( 'button', { name: 'Save chapters' } ) ).toBeEnabled();
	} );

	it( 'keeps the modal open and reports the error when the upload fails', async () => {
		mockUploadTrackForGuid.mockRejectedValue( new Error( 'Upload exploded' ) );
		const { onClose, onSaved } = renderModal();

		await userEvent.type( screen.getAllByLabelText( 'Title' )[ 0 ], '!' );
		await userEvent.click( screen.getByRole( 'button', { name: 'Save chapters' } ) );

		await expect( screen.findByText( 'Upload exploded' ) ).resolves.toBeInTheDocument();
		expect( onSaved ).not.toHaveBeenCalled();
		expect( onClose ).not.toHaveBeenCalled();
		expect( screen.getByRole( 'button', { name: 'Save chapters' } ) ).toBeEnabled();
	} );

	it( 'keeps the modal open when deleting the chapters track fails', async () => {
		mockDeleteTrackForGuid.mockRejectedValue( new Error( 'Delete exploded' ) );
		const { onClose, onSaved } = renderModal( { tracks: [ CHAPTERS_TRACK ] } );

		for ( let i = 0; i < 3; i++ ) {
			await userEvent.click( screen.getAllByLabelText( 'Remove chapter' )[ 0 ] );
		}
		await userEvent.click( screen.getByRole( 'button', { name: 'Save chapters' } ) );

		await expect( screen.findByText( 'Delete exploded' ) ).resolves.toBeInTheDocument();
		expect( onSaved ).not.toHaveBeenCalled();
		expect( onClose ).not.toHaveBeenCalled();
	} );

	it( 'Escape with unsaved edits shows the discard confirmation instead of closing', async () => {
		const { onClose } = renderModal();
		// Focus stays in the title field, inside the body div's Escape interceptor.
		await userEvent.type( screen.getAllByLabelText( 'Title' )[ 0 ], '!' );
		await userEvent.keyboard( '{Escape}' );

		expect( onClose ).not.toHaveBeenCalled();
		expect( screen.getByText( 'Discard unsaved chapter changes?' ) ).toBeInTheDocument();
	} );

	it( 'asks before discarding unsaved edits on close', async () => {
		const { onClose } = renderModal();
		await userEvent.type( screen.getAllByLabelText( 'Title' )[ 0 ], '!' );
		await userEvent.click( screen.getByRole( 'button', { name: 'Close dialog' } ) );

		expect( onClose ).not.toHaveBeenCalled();
		expect( screen.getByText( 'Discard unsaved chapter changes?' ) ).toBeInTheDocument();

		await userEvent.click( screen.getByRole( 'button', { name: 'Discard' } ) );
		expect( onClose ).toHaveBeenCalled();
	} );

	it( 'closes without confirmation when pristine', async () => {
		const { onClose } = renderModal();
		await userEvent.click( screen.getByRole( 'button', { name: 'Close dialog' } ) );
		expect( onClose ).toHaveBeenCalled();
	} );
} );
