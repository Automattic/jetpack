import { probeManualTrack } from '..';
import { fetchVideoItem } from '../../../../lib/fetch-video-item';
import { isAutogeneratedChapterFile } from '../../../../lib/video-tracks';
import type { ChaptersProbeVideo } from '..';
import type { WPCOMRestAPIVideosGetEndpointResponseProps } from '../../../../types';

jest.mock( '../../../../lib/fetch-video-item', () => ( {
	__esModule: true,
	fetchVideoItem: jest.fn(),
} ) );
const mockedFetchVideoItem = fetchVideoItem as jest.Mock;

jest.mock( '../../../../lib/video-tracks', () => ( {
	__esModule: true,
	isAutogeneratedChapterFile: jest.fn(),
} ) );
const mockedIsAutogenerated = isAutogeneratedChapterFile as jest.Mock;

const VIDEO: ChaptersProbeVideo = { guid: 'abc123', isPrivate: false };

const EXISTING_TRACK = { tracks: { chapters: { en: { src: 'chapters.vtt', label: 'English' } } } };
const NO_TRACKS = { tracks: {} };

/**
 * Build a video item whose chapters track has the given src.
 *
 * @param src - The chapters track src.
 * @return A minimal video item.
 */
function itemWithTrackSrc( src: unknown ) {
	return {
		tracks: { chapters: { en: { src } } },
	} as unknown as WPCOMRestAPIVideosGetEndpointResponseProps;
}

describe( 'probeManualTrack', () => {
	beforeEach( () => {
		jest.clearAllMocks();
		mockedFetchVideoItem.mockResolvedValue( NO_TRACKS );
		mockedIsAutogenerated.mockResolvedValue( true );
	} );

	it( 'reports editable without probing the file when the video has no chapters track', async () => {
		await expect( probeManualTrack( VIDEO ) ).resolves.toBe( 'editable' );

		expect( mockedFetchVideoItem ).toHaveBeenCalledWith( { guid: 'abc123', isPrivate: false } );
		expect( mockedIsAutogenerated ).not.toHaveBeenCalled();
	} );

	it( 'treats an empty-string track src like a missing track', async () => {
		mockedFetchVideoItem.mockResolvedValue( itemWithTrackSrc( '' ) );

		await expect( probeManualTrack( VIDEO ) ).resolves.toBe( 'editable' );

		expect( mockedIsAutogenerated ).not.toHaveBeenCalled();
	} );

	it( 'treats a non-string track src like a missing track', async () => {
		mockedFetchVideoItem.mockResolvedValue( itemWithTrackSrc( { nested: 'oops' } ) );

		await expect( probeManualTrack( VIDEO ) ).resolves.toBe( 'editable' );

		expect( mockedIsAutogenerated ).not.toHaveBeenCalled();
	} );

	it( 'reports editable when the existing chapters file is auto-generated', async () => {
		mockedFetchVideoItem.mockResolvedValue( EXISTING_TRACK );
		mockedIsAutogenerated.mockResolvedValue( true );

		await expect( probeManualTrack( VIDEO ) ).resolves.toBe( 'editable' );

		expect( mockedIsAutogenerated ).toHaveBeenCalledWith(
			'https://videos.files.wordpress.com/abc123/chapters.vtt',
			{ guid: 'abc123', isPrivate: false }
		);
	} );

	it( 'reports manual when the existing chapters file is not auto-generated', async () => {
		mockedFetchVideoItem.mockResolvedValue( EXISTING_TRACK );
		mockedIsAutogenerated.mockResolvedValue( false );

		await expect( probeManualTrack( VIDEO ) ).resolves.toBe( 'manual' );
	} );

	it( 'passes the private flag through so the probe can sign its file request', async () => {
		mockedFetchVideoItem.mockResolvedValue( EXISTING_TRACK );
		mockedIsAutogenerated.mockResolvedValue( false );

		await expect( probeManualTrack( { guid: 'priv456', isPrivate: true } ) ).resolves.toBe(
			'manual'
		);

		expect( mockedFetchVideoItem ).toHaveBeenCalledWith( { guid: 'priv456', isPrivate: true } );
		expect( mockedIsAutogenerated ).toHaveBeenCalledWith(
			'https://videos.files.wordpress.com/priv456/chapters.vtt',
			{ guid: 'priv456', isPrivate: true }
		);
	} );

	it( 'fails open to editable when fetching the video item rejects', async () => {
		mockedFetchVideoItem.mockRejectedValue( new Error( 'network down' ) );

		await expect( probeManualTrack( VIDEO ) ).resolves.toBe( 'editable' );

		expect( mockedIsAutogenerated ).not.toHaveBeenCalled();
	} );

	it( 'fails open to editable when the file probe itself rejects', async () => {
		mockedFetchVideoItem.mockResolvedValue( EXISTING_TRACK );
		mockedIsAutogenerated.mockRejectedValue( new Error( 'fetch failed' ) );

		await expect( probeManualTrack( VIDEO ) ).resolves.toBe( 'editable' );
	} );

	it( 'reuses a caller-provided item instead of fetching the video again', async () => {
		mockedIsAutogenerated.mockResolvedValue( false );

		await expect(
			probeManualTrack( VIDEO, {
				item: EXISTING_TRACK as unknown as WPCOMRestAPIVideosGetEndpointResponseProps,
			} )
		).resolves.toBe( 'manual' );

		expect( mockedFetchVideoItem ).not.toHaveBeenCalled();
		expect( mockedIsAutogenerated ).toHaveBeenCalledWith(
			'https://videos.files.wordpress.com/abc123/chapters.vtt',
			{ guid: 'abc123', isPrivate: false }
		);
	} );

	it( 'builds the probed URL by prefixing the filename with the video file base', async () => {
		mockedFetchVideoItem.mockResolvedValue( itemWithTrackSrc( 'my-chapters_en.vtt' ) );

		await probeManualTrack( VIDEO );

		expect( mockedIsAutogenerated ).toHaveBeenCalledWith(
			'https://videos.files.wordpress.com/abc123/my-chapters_en.vtt',
			{ guid: 'abc123', isPrivate: false }
		);
	} );

	it( 'prefixes even an absolute src with the file base (current behavior)', async () => {
		// The v1.1 videos endpoint returns bare filenames for track srcs, so the
		// implementation prefixes unconditionally; an absolute URL in `src` is
		// not detected and gets prefixed too. Pinned here so a change to that
		// assumption is a deliberate one.
		mockedFetchVideoItem.mockResolvedValue(
			itemWithTrackSrc( 'https://example.com/chapters.vtt' )
		);

		await probeManualTrack( VIDEO );

		expect( mockedIsAutogenerated ).toHaveBeenCalledWith(
			'https://videos.files.wordpress.com/abc123/https://example.com/chapters.vtt',
			{ guid: 'abc123', isPrivate: false }
		);
	} );
} );
