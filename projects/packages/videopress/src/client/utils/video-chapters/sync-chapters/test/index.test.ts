import { syncChapters } from '..';
import { fetchVideoItem } from '../../../../lib/fetch-video-item';
import {
	deleteTrackForGuid,
	isAutogeneratedChapterFile,
	uploadTrackForGuid,
} from '../../../../lib/video-tracks';
import generateChaptersFile from '../../generate-chapters-file';
import type { ChaptersSyncVideo } from '..';

jest.mock( '../../../../lib/fetch-video-item', () => ( {
	__esModule: true,
	fetchVideoItem: jest.fn(),
} ) );
const mockedFetchVideoItem = fetchVideoItem as jest.Mock;

jest.mock( '../../../../lib/video-tracks', () => ( {
	__esModule: true,
	deleteTrackForGuid: jest.fn(),
	isAutogeneratedChapterFile: jest.fn(),
	uploadTrackForGuid: jest.fn(),
} ) );
const mockedIsAutogenerated = isAutogeneratedChapterFile as jest.Mock;
const mockedUploadTrack = uploadTrackForGuid as jest.Mock;
const mockedDeleteTrack = deleteTrackForGuid as jest.Mock;

jest.mock( '../../generate-chapters-file', () => ( {
	__esModule: true,
	default: jest.fn(),
} ) );
const mockedGenerateChaptersFile = generateChaptersFile as jest.Mock;

const onWarning = jest.fn();

// Three chapters, first at 0:00, titled, 30s apart — passes the validator.
const VALID_DESCRIPTION = [
	'A tour of the video.',
	'',
	'00:00 Intro',
	'00:30 Editing',
	'01:00 Export',
].join( '\n' );

const PROSE_DESCRIPTION = 'Just prose now — the timestamps are gone.';

const EXISTING_TRACK = { tracks: { chapters: { en: { src: 'chapters.vtt', label: 'English' } } } };
const NO_TRACKS = { tracks: {} };

const VIDEO: ChaptersSyncVideo = { guid: 'abc123', isPrivate: false, durationSeconds: 90 };

describe( 'syncChapters', () => {
	const generatedFile = new File( [ 'WEBVTT' ], 'chapters.vtt', { type: 'text/vtt' } );

	beforeEach( () => {
		jest.clearAllMocks();
		mockedFetchVideoItem.mockResolvedValue( NO_TRACKS );
		mockedIsAutogenerated.mockResolvedValue( true );
		mockedUploadTrack.mockResolvedValue( 'chapters.vtt' );
		mockedDeleteTrack.mockResolvedValue( {} );
		mockedGenerateChaptersFile.mockReturnValue( generatedFile );
	} );

	it( 'uploads a regenerated track with the real video duration when no track exists', async () => {
		await expect( syncChapters( VIDEO, VALID_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'uploaded'
		);

		// The generator receives the video's actual duration in milliseconds,
		// not the legacy 999:59:59 sentinel, so the last cue ends at video end.
		expect( mockedGenerateChaptersFile ).toHaveBeenCalledWith( VALID_DESCRIPTION, 90000 );
		expect( mockedUploadTrack ).toHaveBeenCalledWith(
			{
				label: 'English (auto-generated)',
				srcLang: 'en',
				kind: 'chapters',
				tmpFile: generatedFile,
			},
			'abc123'
		);
		// No existing file means nothing to probe and nothing to delete.
		expect( mockedIsAutogenerated ).not.toHaveBeenCalled();
		expect( mockedDeleteTrack ).not.toHaveBeenCalled();
		expect( onWarning ).not.toHaveBeenCalled();
	} );

	it( 'overwrites an existing track after confirming it is auto-generated', async () => {
		mockedFetchVideoItem.mockResolvedValue( EXISTING_TRACK );

		await expect( syncChapters( VIDEO, VALID_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'uploaded'
		);

		expect( mockedIsAutogenerated ).toHaveBeenCalledWith(
			'https://videos.files.wordpress.com/abc123/chapters.vtt',
			{ guid: 'abc123', isPrivate: false }
		);
		expect( mockedUploadTrack ).toHaveBeenCalled();
	} );

	it( 'never overwrites a manually uploaded chapters track', async () => {
		mockedFetchVideoItem.mockResolvedValue( EXISTING_TRACK );
		mockedIsAutogenerated.mockResolvedValue( false );

		await expect( syncChapters( VIDEO, VALID_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'skipped-manual'
		);

		expect( mockedUploadTrack ).not.toHaveBeenCalled();
		expect( mockedDeleteTrack ).not.toHaveBeenCalled();
		expect( onWarning ).not.toHaveBeenCalled();
	} );

	it( 'deletes the auto-generated track when the description no longer has valid chapters', async () => {
		mockedFetchVideoItem.mockResolvedValue( EXISTING_TRACK );

		await expect( syncChapters( VIDEO, PROSE_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'deleted'
		);

		expect( mockedDeleteTrack ).toHaveBeenCalledWith(
			{ kind: 'chapters', srcLang: 'en' },
			'abc123'
		);
		expect( mockedUploadTrack ).not.toHaveBeenCalled();
		expect( onWarning ).not.toHaveBeenCalled();
	} );

	it( 'leaves a manually uploaded track alone even when the description has no chapters', async () => {
		mockedFetchVideoItem.mockResolvedValue( EXISTING_TRACK );
		mockedIsAutogenerated.mockResolvedValue( false );

		await expect( syncChapters( VIDEO, PROSE_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'skipped-manual'
		);

		expect( mockedDeleteTrack ).not.toHaveBeenCalled();
	} );

	it( 'does nothing when there are no valid chapters and no track', async () => {
		await expect( syncChapters( VIDEO, PROSE_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'unchanged'
		);

		expect( mockedIsAutogenerated ).not.toHaveBeenCalled();
		expect( mockedUploadTrack ).not.toHaveBeenCalled();
		expect( mockedDeleteTrack ).not.toHaveBeenCalled();
		expect( onWarning ).not.toHaveBeenCalled();
	} );

	it( 'raises a warning and resolves (never rejects) when the upload fails', async () => {
		mockedUploadTrack.mockRejectedValue( new Error( 'boom' ) );

		await expect( syncChapters( VIDEO, VALID_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'error'
		);

		expect( onWarning ).toHaveBeenCalledWith( 'Video chapters could not be updated.' );
	} );

	it( 'treats a WPCOM error envelope from the tracks endpoint as a failure', async () => {
		// The tracks endpoints respond 200 with `{ error }` instead of
		// rejecting, so the envelope must be treated as a failure explicitly.
		mockedUploadTrack.mockResolvedValue( { error: 'unauthorized' } );

		await expect( syncChapters( VIDEO, VALID_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'error'
		);

		expect( onWarning ).toHaveBeenCalledWith( 'Video chapters could not be updated.' );
	} );

	it( 'resolves as an error when the track probe itself fails', async () => {
		mockedFetchVideoItem.mockRejectedValue( new Error( 'network down' ) );

		await expect( syncChapters( VIDEO, VALID_DESCRIPTION, { onWarning } ) ).resolves.toBe(
			'error'
		);

		expect( mockedUploadTrack ).not.toHaveBeenCalled();
		expect( mockedDeleteTrack ).not.toHaveBeenCalled();
		expect( onWarning ).toHaveBeenCalledWith( 'Video chapters could not be updated.' );
	} );

	it( 'still resolves as an error when no warning callback is provided', async () => {
		mockedUploadTrack.mockRejectedValue( new Error( 'boom' ) );

		await expect( syncChapters( VIDEO, VALID_DESCRIPTION ) ).resolves.toBe( 'error' );
	} );
} );
