/**
 * Studio port of the legacy dashboard's chapters pipeline
 * (`use-edit-details.ts` → `handleChaptersUpdate`): the player consumes a
 * WebVTT 'chapters' track that is generated from timestamp lines in the
 * video description, so a description save must regenerate that track or
 * the player's chapter menu silently de-syncs. The legacy libs are reused
 * via cross-tree imports (same precedent as `./use-upload.ts`).
 *
 * Differences from the legacy flow, both deliberate:
 * - `generateChaptersFile` receives the video's real duration, so the last
 * cue ends at the video end instead of the legacy 999:59:59 sentinel.
 * - When the description no longer holds valid chapters but an
 * auto-generated track still exists, the track is deleted — legacy left
 * it stale on the player.
 *
 * A manually uploaded chapters VTT is never touched: the auto-generated
 * marker (`NOTE videopress-chapters-auto-generated`) is the overwrite
 * guard, exactly as in legacy. Only the `en` track is handled — a known
 * limitation carried over from the legacy pipeline.
 */
import { useGlobalNotices } from '@automattic/jetpack-components/global-notices';
import { useCallback } from '@wordpress/element';
import { __ } from '@wordpress/i18n';
import { fetchVideoItem } from '../../client/lib/fetch-video-item';
import {
	deleteTrackForGuid,
	isAutogeneratedChapterFile,
	uploadTrackForGuid,
} from '../../client/lib/video-tracks';
import generateChaptersFile from '../../client/utils/video-chapters/generate-chapters-file';
import { parseDescription, validateRows } from '../utils/chapters';
import type { LibraryItem } from '../types/library';

export type ChaptersSyncStatus =
	/** A regenerated VTT was uploaded over no track or an auto-generated one. */
	| 'uploaded'
	/** The stale auto-generated track was removed from the player. */
	| 'deleted'
	/** A manually uploaded chapters VTT exists — never overwritten. */
	| 'skipped-manual'
	/** No valid chapters in the description and no track to remove. */
	| 'unchanged'
	/** Something failed; a warning notice was raised. */
	| 'error';

type ChaptersVideo = Pick< LibraryItem, 'guid' | 'isPrivate' | 'durationSeconds' >;

/**
 * Detect the WPCOM error envelope that the tracks endpoints resolve with on
 * failure (they respond 200 with `{ error }` instead of rejecting).
 *
 * @param value - A settled tracks-endpoint response.
 * @return Whether the response is an error envelope.
 */
const isErrorEnvelope = ( value: unknown ): value is { error: string; message?: string } =>
	typeof value === 'object' && value !== null && 'error' in value;

/**
 * Return a `syncChapters` callback that reconciles the video's chapters VTT
 * track with its (about-to-be-saved) description.
 *
 * The callback never rejects: every failure resolves as `'error'` after
 * raising a warning notice, so callers can fire it alongside the details
 * save without the save being blocked or failed by the chapters sync.
 *
 * @return An object with the stable `syncChapters` callback.
 */
export function useUpdateChapters() {
	const { createWarningNotice } = useGlobalNotices();

	const syncChapters = useCallback(
		async ( video: ChaptersVideo, description: string ): Promise< ChaptersSyncStatus > => {
			const { rows } = parseDescription( description );
			const hasValidChapters = validateRows( rows, video.durationSeconds ).isValid;

			try {
				const item = await fetchVideoItem( { guid: video.guid, isPrivate: video.isPrivate } );
				const trackSrc = item?.tracks?.chapters?.en?.src;
				const hasTrack = typeof trackSrc === 'string' && trackSrc !== '';

				if ( ! hasValidChapters && ! hasTrack ) {
					return 'unchanged';
				}

				if ( hasTrack ) {
					const trackUrl = `https://videos.files.wordpress.com/${ video.guid }/${ trackSrc }`;
					const isAutogenerated = await isAutogeneratedChapterFile( trackUrl, {
						guid: video.guid,
						isPrivate: video.isPrivate,
					} );

					if ( ! isAutogenerated ) {
						return 'skipped-manual';
					}
				}

				if ( ! hasValidChapters ) {
					// The auto-generated track no longer matches any chapters in
					// the description: remove it so the player drops the menu.
					const deleted = await deleteTrackForGuid(
						{ kind: 'chapters', srcLang: 'en' },
						video.guid
					);
					if ( isErrorEnvelope( deleted ) ) {
						throw new Error( deleted.message || deleted.error );
					}
					return 'deleted';
				}

				// Real duration (ms) for the final cue's end time; fall back to
				// the generator's own sentinel when the duration is unknown.
				const durationMs = video.durationSeconds > 0 ? video.durationSeconds * 1000 : undefined;
				const tmpFile = generateChaptersFile( description, durationMs );
				if ( ! tmpFile ) {
					// Unreachable: validation passed, so the description has chapters.
					throw new Error( 'Failed to generate the chapters file' );
				}

				const uploaded = await uploadTrackForGuid(
					{
						label: __( 'English (auto-generated)', 'jetpack-videopress-pkg' ),
						srcLang: 'en',
						kind: 'chapters',
						tmpFile,
					},
					video.guid
				);
				if ( isErrorEnvelope( uploaded ) ) {
					throw new Error( uploaded.message || uploaded.error );
				}
				return 'uploaded';
			} catch {
				createWarningNotice(
					__( 'Video chapters could not be updated.', 'jetpack-videopress-pkg' )
				);
				return 'error';
			}
		},
		[ createWarningNotice ]
	);

	return { syncChapters };
}
