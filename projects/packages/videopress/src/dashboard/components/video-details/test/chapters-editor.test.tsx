import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { fetchVideoItem } from '../../../../client/lib/fetch-video-item';
import { isAutogeneratedChapterFile } from '../../../../client/lib/video-tracks';
import ChaptersEditor, { parseClockTime } from '../chapters-editor';

jest.mock( '../../../../client/lib/fetch-video-item', () => ( {
	__esModule: true,
	fetchVideoItem: jest.fn(),
} ) );
const mockedFetchVideoItem = fetchVideoItem as jest.Mock;

jest.mock( '../../../../client/lib/video-tracks', () => ( {
	__esModule: true,
	isAutogeneratedChapterFile: jest.fn(),
} ) );
const mockedIsAutogenerated = isAutogeneratedChapterFile as jest.Mock;

const VIDEO = { guid: 'abc123', isPrivate: false, durationSeconds: 300 };

// Three valid chapters with surrounding prose, exercising the lens rules.
const DESCRIPTION = [
	'A video about things.',
	'',
	'00:00 Intro',
	'00:30 Middle',
	'01:10 End',
	'',
	'Thanks for watching!',
].join( '\n' );

const renderEditor = ( overrides: { description?: string } = {} ) => {
	const onChange = jest.fn();
	const onOpenHelp = jest.fn();
	const utils = render(
		<ChaptersEditor
			video={ VIDEO }
			description={ overrides.description ?? DESCRIPTION }
			onChange={ onChange }
			onOpenHelp={ onOpenHelp }
		/>
	);
	return { ...utils, onChange, onOpenHelp };
};

const expandEditor = async () => {
	await userEvent.click( screen.getByRole( 'button', { name: /^Chapters \(/ } ) );
	// The expand triggers the manual-track probe; wait for it to settle so no
	// state update lands outside act() after the test body.
	await waitFor( () => expect( mockedFetchVideoItem ).toHaveBeenCalled() );
};

beforeEach( () => {
	jest.clearAllMocks();
	// Default probe: no chapters track exists → editable.
	mockedFetchVideoItem.mockResolvedValue( { tracks: {} } );
	mockedIsAutogenerated.mockResolvedValue( true );
} );

describe( 'parseClockTime', () => {
	it.each( [
		[ '90', 90 ],
		[ '1:30', 90 ],
		[ '01:30', 90 ],
		[ '1:00:05', 3605 ],
		[ '(2:00)', 120 ],
		[ ' 0:00 ', 0 ],
	] )( 'parses %s to %d seconds', ( text, expected ) => {
		expect( parseClockTime( text ) ).toBe( expected );
	} );

	it.each( [ [ 'abc' ], [ '1:99' ], [ '1:2:3:4' ], [ '' ] ] )( 'rejects %s', text => {
		expect( parseClockTime( text ) ).toBeNull();
	} );
} );

describe( 'ChaptersEditor', () => {
	it( 'is collapsed by default, with the parsed chapter count in the toggle', () => {
		renderEditor();

		expect( screen.getByRole( 'button', { name: 'Chapters (3)' } ) ).toHaveAttribute(
			'aria-expanded',
			'false'
		);
		expect( screen.queryByLabelText( 'Chapter 1 title' ) ).not.toBeInTheDocument();
	} );

	it( 'expands to one row per recognized chapter line, in document order', async () => {
		renderEditor();
		await expandEditor();

		expect( screen.getByLabelText( 'Chapter 1 time' ) ).toHaveValue( '00:00' );
		expect( screen.getByLabelText( 'Chapter 1 title' ) ).toHaveValue( 'Intro' );
		expect( screen.getByLabelText( 'Chapter 2 time' ) ).toHaveValue( '00:30' );
		expect( screen.getByLabelText( 'Chapter 3 title' ) ).toHaveValue( 'End' );
	} );

	it( 'commits a title edit on blur by serializing into the description', async () => {
		const { onChange } = renderEditor();
		await expandEditor();

		const title = screen.getByLabelText( 'Chapter 2 title' );
		await userEvent.clear( title );
		await userEvent.type( title, 'Deep dive' );
		await userEvent.tab();

		expect( onChange ).toHaveBeenCalledTimes( 1 );
		const { description } = onChange.mock.calls[ 0 ][ 0 ];
		expect( description ).toContain( '0:30 Deep dive' );
		expect( description ).toContain( 'A video about things.' );
		expect( description ).toContain( 'Thanks for watching!' );
	} );

	it( 'reverts an unparseable time on blur without touching the description', async () => {
		const { onChange } = renderEditor();
		await expandEditor();

		const time = screen.getByLabelText( 'Chapter 2 time' );
		await userEvent.clear( time );
		await userEvent.type( time, 'garbage' );
		await userEvent.tab();

		expect( onChange ).not.toHaveBeenCalled();
		expect( time ).toHaveValue( '00:30' );
	} );

	it( 'adds a chapter seeded 10s after the last row', async () => {
		const { onChange } = renderEditor();
		await expandEditor();

		await userEvent.click( screen.getByRole( 'button', { name: 'Add chapter' } ) );

		const { description } = onChange.mock.calls[ 0 ][ 0 ];
		expect( description ).toContain( '1:20 New chapter' );
	} );

	it( 'removes a chapter row', async () => {
		const { onChange } = renderEditor();
		await expandEditor();

		await userEvent.click( screen.getByRole( 'button', { name: 'Remove chapter 2' } ) );

		const { description } = onChange.mock.calls[ 0 ][ 0 ];
		expect( description ).not.toContain( 'Middle' );
		expect( description ).toContain( '0:00 Intro' );
		expect( description ).toContain( '1:10 End' );
	} );

	it( 'shows the validation summary for invalid chapters without blocking edits', async () => {
		renderEditor( { description: '00:00 Only\n00:05 Close' } );
		await expandEditor();

		expect( screen.getByRole( 'status' ) ).toBeInTheDocument();
		// Both issues surface: too few chapters and rows closer than 10s.
		expect( screen.getByRole( 'status' ) ).toHaveTextContent( /chapters/i );
		expect( screen.getByLabelText( 'Chapter 1 title' ) ).toBeEnabled();
	} );

	it( 'hides the validation summary when chapters are valid', async () => {
		renderEditor();
		await expandEditor();

		expect( screen.queryByRole( 'status' ) ).not.toBeInTheDocument();
	} );

	it( 'replaces the editor with a read-only notice when a manual VTT exists', async () => {
		mockedFetchVideoItem.mockResolvedValue( {
			tracks: { chapters: { en: { src: 'manual.vtt' } } },
		} );
		mockedIsAutogenerated.mockResolvedValue( false );

		renderEditor();
		await expandEditor();

		await expect(
			screen.findByText( /managed by an uploaded VTT file/ )
		).resolves.toBeInTheDocument();
		expect( screen.queryByLabelText( 'Chapter 1 title' ) ).not.toBeInTheDocument();
	} );

	it( 'keeps the editor editable when the probe fails (fail open)', async () => {
		mockedFetchVideoItem.mockRejectedValue( new Error( 'network' ) );

		renderEditor();
		await expandEditor();

		await expect( screen.findByLabelText( 'Chapter 1 title' ) ).resolves.toBeInTheDocument();
	} );

	it( 'opens the help modal from the header link', async () => {
		const { onOpenHelp } = renderEditor();

		await userEvent.click( screen.getByRole( 'link', { name: /Learn how chapters work/ } ) );

		expect( onOpenHelp ).toHaveBeenCalled();
	} );
} );
