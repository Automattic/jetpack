/**
 * Structured chapters editor: a pure lens over the description string.
 *
 * The description stays the single source of truth — rows are derived via
 * parseDescription() and every committed edit writes back through
 * serializeDescription() into the same form field the description textarea
 * binds, so the two stay views of one value with no second store. Rows keep
 * DOCUMENT order (serializeDescription maps rows positionally onto the
 * recognized lines); ordering problems surface through validateRows()
 * instead of being silently reshuffled.
 *
 * Field edits are held in LOCAL draft state and committed on blur/Enter — a
 * half-typed `1:2` must never round-trip through parse mid-keystroke.
 *
 * Invalid chapters never block saving the description; they only mean the
 * chapters VTT will not be (re)generated on save — the same semantics as
 * use-update-chapters. When a manually uploaded chapters VTT exists the
 * editor is replaced by a read-only notice (probed lazily on first expand;
 * probe failures fail OPEN, since use-update-chapters re-checks the guard
 * at write time anyway).
 */
import { useEffect, useMemo, useRef, useState } from '@wordpress/element';
import { __, sprintf } from '@wordpress/i18n';
import { closeSmall } from '@wordpress/icons';
import { Button, IconButton, InputControl, Link, Stack, Text } from '@wordpress/ui';
import { fetchVideoItem } from '../../../client/lib/fetch-video-item';
import { isAutogeneratedChapterFile } from '../../../client/lib/video-tracks';
import { parseDescription, serializeDescription, validateRows } from '../../utils/chapters';
import { formatDuration } from '../../utils/format';
import type { LibraryItem } from '../../types/library';
import type { ChapterRow } from '../../utils/chapters';
import type { ReactElement } from 'react';

type ChaptersVideo = Pick< LibraryItem, 'guid' | 'isPrivate' | 'durationSeconds' >;

type Props = {
	video: ChaptersVideo;
	description: string;
	onChange: ( partial: { description?: string } ) => void;
	onOpenHelp: () => void;
};

/** Result of the lazy manual-track probe. */
type TrackProbe = 'unprobed' | 'probing' | 'manual' | 'editable';

/**
 * Parse a user-typed clock time (`SS`, `MM:SS`, `H:MM:SS`, optional
 * parentheses/whitespace) to total seconds.
 *
 * @param text - The typed time.
 * @return Total seconds, or null when unparseable.
 */
export function parseClockTime( text: string ): number | null {
	const cleaned = text.replace( /[()]/g, '' ).trim();
	if ( ! /^\d{1,3}(:[0-5]?\d){0,2}$/.test( cleaned ) ) {
		return null;
	}
	const parts = cleaned.split( ':' ).map( Number );
	return parts.reduce( ( total, part ) => total * 60 + part, 0 );
}

/**
 * Probe whether the video carries a MANUALLY uploaded chapters VTT (which
 * this editor must never touch). Fails open: any probe error reports
 * 'editable', because the save-time sync re-checks the guard authoritatively.
 *
 * @param video - The video to probe.
 * @return Whether the chapters track is manual or safe to edit.
 */
async function probeManualTrack( video: ChaptersVideo ): Promise< 'manual' | 'editable' > {
	try {
		const item = await fetchVideoItem( { guid: video.guid, isPrivate: video.isPrivate } );
		const trackSrc = item?.tracks?.chapters?.en?.src;
		if ( typeof trackSrc !== 'string' || trackSrc === '' ) {
			return 'editable';
		}
		const trackUrl = `https://videos.files.wordpress.com/${ video.guid }/${ trackSrc }`;
		const isAutogenerated = await isAutogeneratedChapterFile( trackUrl, {
			guid: video.guid,
			isPrivate: video.isPrivate,
		} );
		return isAutogenerated ? 'editable' : 'manual';
	} catch {
		return 'editable';
	}
}

/**
 * One chapter row: time + title inputs with local drafts committed on
 * blur/Enter, and a remove button.
 *
 * @param props          - Component props.
 * @param props.row      - The committed row values.
 * @param props.index    - Row position (for labels).
 * @param props.onCommit - Called with the updated row on commit.
 * @param props.onRemove - Removes the row.
 * @return The row element.
 */
function ChapterRowFields( {
	row,
	index,
	onCommit,
	onRemove,
}: {
	row: ChapterRow;
	index: number;
	onCommit: ( next: ChapterRow ) => void;
	onRemove: () => void;
} ): ReactElement {
	const [ timeDraft, setTimeDraft ] = useState( () => formatDuration( row.startAtSeconds ) );
	const [ titleDraft, setTitleDraft ] = useState( row.title );

	// Re-baseline drafts when the committed row changes underneath us (e.g.
	// the user edited the description textarea directly).
	useEffect( () => {
		setTimeDraft( formatDuration( row.startAtSeconds ) );
		setTitleDraft( row.title );
	}, [ row.startAtSeconds, row.title ] );

	const commitTime = () => {
		const seconds = parseClockTime( timeDraft );
		if ( seconds === null ) {
			// Unparseable: revert the draft, never round-trip garbage.
			setTimeDraft( formatDuration( row.startAtSeconds ) );
			return;
		}
		setTimeDraft( formatDuration( seconds ) );
		if ( seconds !== row.startAtSeconds ) {
			onCommit( { ...row, startAtSeconds: seconds } );
		}
	};

	const commitTitle = () => {
		// Newlines would break the description's line structure.
		const title = titleDraft.replace( /\s*\n\s*/g, ' ' ).trim();
		setTitleDraft( title );
		if ( title !== row.title ) {
			onCommit( { ...row, title } );
		}
	};

	return (
		<Stack direction="row" gap="sm" align="end" className="vp-chapters-editor__row">
			<InputControl
				className="vp-chapters-editor__time"
				label={ sprintf(
					/* translators: %d: 1-based chapter number. */
					__( 'Chapter %d time', 'jetpack-videopress-pkg' ),
					index + 1
				) }
				value={ timeDraft }
				onValueChange={ next => setTimeDraft( next ?? '' ) }
				onBlur={ commitTime }
				onKeyDown={ event => {
					if ( event.key === 'Enter' ) {
						commitTime();
					}
				} }
			/>
			<InputControl
				className="vp-chapters-editor__title"
				label={ sprintf(
					/* translators: %d: 1-based chapter number. */
					__( 'Chapter %d title', 'jetpack-videopress-pkg' ),
					index + 1
				) }
				value={ titleDraft }
				onValueChange={ next => setTitleDraft( next ?? '' ) }
				onBlur={ commitTitle }
				onKeyDown={ event => {
					if ( event.key === 'Enter' ) {
						commitTitle();
					}
				} }
			/>
			<IconButton
				label={ sprintf(
					/* translators: %d: 1-based chapter number. */
					__( 'Remove chapter %d', 'jetpack-videopress-pkg' ),
					index + 1
				) }
				icon={ closeSmall }
				size="small"
				variant="minimal"
				tone="neutral"
				onClick={ onRemove }
			/>
		</Stack>
	);
}

/**
 * The collapsed-by-default "Chapters (N)" editor for the Details card.
 *
 * @param props             - Component props.
 * @param props.video       - The video (guid/privacy for the probe, duration for validation).
 * @param props.description - The form's current description value.
 * @param props.onChange    - The form's partial-update handler.
 * @param props.onOpenHelp  - Opens the chapters help modal.
 * @return The editor element.
 */
export default function ChaptersEditor( {
	video,
	description,
	onChange,
	onOpenHelp,
}: Props ): ReactElement {
	const [ isExpanded, setIsExpanded ] = useState( false );
	const [ probe, setProbe ] = useState< TrackProbe >( 'unprobed' );
	const probeStarted = useRef( false );

	const { rows } = useMemo( () => parseDescription( description ), [ description ] );
	const validation = useMemo(
		() => validateRows( rows, video.durationSeconds ),
		[ rows, video.durationSeconds ]
	);

	// Probe for a manual VTT lazily, on first expand only.
	useEffect( () => {
		if ( ! isExpanded || probeStarted.current ) {
			return;
		}
		probeStarted.current = true;
		setProbe( 'probing' );
		let isCancelled = false;
		probeManualTrack( video ).then( result => {
			if ( ! isCancelled ) {
				setProbe( result );
			}
		} );
		return () => {
			isCancelled = true;
		};
		// The probeStarted ref makes this once-per-mount even if the video
		// object identity changes on refetch.
	}, [ isExpanded, video ] );

	const commitRows = ( nextRows: ChapterRow[] ) => {
		onChange( { description: serializeDescription( description, nextRows ) } );
	};

	const addChapter = () => {
		const last = rows[ rows.length - 1 ];
		const startAtSeconds = last ? last.startAtSeconds + 10 : 0;
		commitRows( [
			...rows,
			{ startAtSeconds, title: __( 'New chapter', 'jetpack-videopress-pkg' ) },
		] );
	};

	return (
		<div className="vp-chapters-editor">
			<Stack direction="row" gap="sm" align="center" justify="space-between">
				<Button
					variant="tertiary"
					aria-expanded={ isExpanded }
					onClick={ () => setIsExpanded( current => ! current ) }
				>
					{ sprintf(
						/* translators: %d: number of chapters in the description. */
						__( 'Chapters (%d)', 'jetpack-videopress-pkg' ),
						rows.length
					) }
				</Button>
				<Link
					href="#"
					onClick={ event => {
						event.preventDefault();
						onOpenHelp();
					} }
				>
					{ __( 'Learn how chapters work', 'jetpack-videopress-pkg' ) }
				</Link>
			</Stack>

			{ isExpanded && probe === 'manual' && (
				<Text variant="body-sm" className="vp-chapters-editor__manual-notice">
					{ __(
						'Chapters for this video are managed by an uploaded VTT file, so they can’t be edited here.',
						'jetpack-videopress-pkg'
					) }
				</Text>
			) }

			{ isExpanded && probe !== 'manual' && (
				<Stack direction="column" gap="sm" className="vp-chapters-editor__body">
					{ rows.map( ( row, index ) => (
						<ChapterRowFields
							// Positional identity is correct here: rows ARE the
							// recognized description lines, in document order.
							key={ index }
							row={ row }
							index={ index }
							onCommit={ next => commitRows( rows.map( ( r, i ) => ( i === index ? next : r ) ) ) }
							onRemove={ () => commitRows( rows.filter( ( _, i ) => i !== index ) ) }
						/>
					) ) }
					<div>
						<Button variant="outline" size="compact" onClick={ addChapter }>
							{ __( 'Add chapter', 'jetpack-videopress-pkg' ) }
						</Button>
					</div>
					{ rows.length > 0 && ! validation.isValid && (
						<div className="vp-chapters-editor__issues" role="status">
							<Text variant="body-sm">
								{ __(
									'Chapters publish when: the first starts at 0:00 · at least 3 chapters · every chapter titled · 10s or more apart · within the video.',
									'jetpack-videopress-pkg'
								) }
							</Text>
							<ul>
								{ validation.issues.map( ( issue, index ) => (
									<li key={ `${ issue.code }-${ index }` }>
										<Text variant="body-sm">{ issue.message }</Text>
									</li>
								) ) }
							</ul>
						</div>
					) }
				</Stack>
			) }
		</div>
	);
}
