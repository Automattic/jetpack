/**
 * Manual-chapters-track probe, shared by every chapters editing surface (the
 * Details-tab editor and the Studio editor's Chapters tool).
 *
 * A chapters VTT uploaded by the user must never be regenerated from the
 * description, so editors probe before offering edits. The probe fails OPEN:
 * any error reports 'editable', because `use-update-chapters` re-checks the
 * guard authoritatively at write time — a false 'editable' only shows edit
 * affordances whose save would then skip the VTT sync, while a false
 * 'manual' would lock the user out of a perfectly editable video.
 */
import { fetchVideoItem } from '../../client/lib/fetch-video-item';
import { isAutogeneratedChapterFile } from '../../client/lib/video-tracks';

/**
 * The fields the probe needs from a video.
 */
export type ChaptersProbeVideo = {
	/** The video's VideoPress guid. */
	guid: string;
	/** Whether the video is private (the probe must sign its requests). */
	isPrivate: boolean;
};

/**
 * Probe whether the video carries a MANUALLY uploaded chapters VTT (which
 * the chapters editors must never touch).
 *
 * @param video - The video to probe.
 * @return Whether the chapters track is manual or safe to edit.
 */
export async function probeManualTrack(
	video: ChaptersProbeVideo
): Promise< 'manual' | 'editable' > {
	try {
		const item = await fetchVideoItem( { guid: video.guid, isPrivate: video.isPrivate } );
		const trackSrc = item?.tracks?.chapters?.en?.src;
		if ( typeof trackSrc !== 'string' || trackSrc === '' ) {
			return 'editable';
		}
		const trackUrl = `https://videos.files.wordpress.com/${ video.guid }/${ trackSrc }`;
		const isAutogenerated = await isAutogeneratedChapterFile( trackUrl, {
			guid: video.guid,
			isPrivate: video.isPrivate,
		} );
		return isAutogenerated ? 'editable' : 'manual';
	} catch {
		return 'editable';
	}
}
