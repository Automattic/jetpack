<?php // phpcs:ignore WordPress.Files.FileName.InvalidClassFileName -- Feature entry file, named after the feature, also holds the WPCOM_Earn bootstrap class.
/**
 * An in-wp-admin Monetize page for WordPress.com Simple and WoA sites, replacing
 * Calypso's Earn page.
 *
 * @package automattic/jetpack-mu-wpcom
 */

namespace Automattic\Jetpack\Jetpack_Mu_Wpcom;

use Automattic\Jetpack\Constants;
use Automattic\Jetpack\Feature_Flags\Feature_Flags;
use Automattic\Jetpack\WP_Build_Polyfills\WP_Build_Polyfills;

require_once __DIR__ . '/../../common/wp-build-script-translations.php';
require_once __DIR__ . '/class-wpcom-earn-proxy.php';
require_once __DIR__ . '/../premium-analytics/wordads-section.php';

/**
 * Registers the Monetize admin page and its wp-build assets.
 */
class WPCOM_Earn {

	/**
	 * Gates the page while it is ported from Calypso.
	 */
	const FLAG = 'earn-wp-build';

	/**
	 * Admin page slug. Contains `earn` so wpcom_reorder_submenu() keeps it where the Calypso link sat.
	 */
	const MENU_SLUG = 'jetpack-earn';

	/**
	 * Page name for wp-build, as declared in every routes/wpcom-earn* package.json.
	 *
	 * Deliberately not the menu slug: wp-build derives its own page slug and render
	 * function from this name.
	 */
	const WP_BUILD_PAGE = 'wpcom-earn';

	/**
	 * Render callback generated by wp-build in build/pages/wpcom-earn/page-wp-admin.php.
	 */
	const RENDER_CALLBACK = 'jetpack_mu_wpcom_wpcom_earn_wp_admin_render_page';

	/**
	 * `admin_menu` priority for register_page().
	 */
	const REGISTER_PRIORITY = 999998;

	/**
	 * Global the page's boot script reads its initial state from.
	 */
	const INITIAL_STATE_VAR = 'wpcomEarnInitialState';

	/**
	 * The plan features the page branches on, keyed as the initial state names them.
	 */
	const FEATURES = array(
		'wordads'           => 'wordads',
		'simplePayments'    => 'simple-payments',
		'donations'         => 'donations',
		'premiumContent'    => 'premium-content/container',
		'recurringPayments' => 'recurring-payments',
	);

	/**
	 * Whether this page registered its slug on this request.
	 *
	 * @var bool
	 */
	private static $owns_page = false;

	/**
	 * The hook suffix add_submenu_page() returned, which is the page's screen ID.
	 *
	 * @var string|null
	 */
	private static $screen_id = null;

	/**
	 * The screen ID displaced by alias_screen_id(), or null when nothing is aliased.
	 *
	 * @var string|null
	 */
	private static $displaced_screen_id = null;

	/**
	 * Register the flag, which has to exist for REST and CLI as well as wp-admin.
	 *
	 * @return void
	 */
	public static function register_feature_flag() {
		Feature_Flags::register(
			self::FLAG,
			array(
				'default'     => false,
				'description' => 'Serve the Monetize page in wp-admin instead of linking to Calypso.',
				'owner'       => 'jetpack-mu-wpcom',
			)
		);
	}

	/**
	 * Boot the feature, loading the wp-build assets only on the page itself.
	 *
	 * @return void
	 */
	public static function init() {
		// Without a build the page would render blank, so leave the Calypso link in place.
		if ( ! static::should_register() || ! static::has_build() ) {
			return;
		}

		if ( Constants::is_true( 'IS_ATOMIC' ) ) {
			add_action( 'rest_api_init', array( WPCOM_Earn_Proxy::class, 'register_routes' ) );
		}

		// After Admin_Menu (1000) so a claimed slug is visible, and before wpcom_add_jetpack_submenu()
		// (999999), which skips the Calypso link once this page owns the slug.
		add_action( 'admin_menu', array( static::class, 'register_page' ), self::REGISTER_PRIORITY );

		if ( ! static::is_page_request() ) {
			return;
		}

		self::load_wp_build();

		// wp-build's generated enqueue runs at the default priority 10; the alias is
		// scoped to that one pass so nothing else sees the rewritten screen.
		add_action( 'admin_enqueue_scripts', array( static::class, 'alias_screen_id' ), 9 );
		add_action( 'admin_enqueue_scripts', array( static::class, 'restore_screen_id' ), 11 );
		add_action( 'admin_enqueue_scripts', array( static::class, 'enqueue_initial_state' ), 20 );
		add_action( 'admin_enqueue_scripts', array( static::class, 'enqueue_script_translations' ), 20 );
		add_filter( 'jetpack_display_jitms_on_screen', array( static::class, 'hide_jitms' ), 10, 2 );
	}

	/**
	 * Whether this page should claim its slug at all.
	 *
	 * @return bool
	 */
	public static function should_register() {
		return Feature_Flags::is_enabled( self::FLAG );
	}

	/**
	 * The wp-build output directory, produced at release time and absent from an unbuilt checkout.
	 *
	 * @return string
	 */
	public static function build_dir() {
		return dirname( __DIR__, 3 ) . '/build';
	}

	/**
	 * Whether the wp-build output this page renders from exists.
	 *
	 * @return bool
	 */
	public static function has_build() {
		return file_exists( static::build_dir() . '/build.php' );
	}

	/**
	 * The page's wp-build route directories, read from the build's route registry.
	 *
	 * @return string[]
	 */
	public static function get_routes() {
		$registry = static::build_dir() . '/routes/registry.php';

		if ( ! file_exists( $registry ) ) {
			return array();
		}

		$routes = array();
		foreach ( (array) require $registry as $route ) {
			if ( is_array( $route ) && static::WP_BUILD_PAGE === ( $route['page'] ?? null ) && isset( $route['name'] ) ) {
				$routes[] = $route['name'];
			}
		}

		return $routes;
	}

	/**
	 * Whether the current request targets this admin page.
	 *
	 * @return bool
	 */
	public static function is_page_request() {
		// admin-ajax.php is also `is_admin()`, and has no menu, screen or enqueue pass to set up.
		if ( ! is_admin() || 'admin.php' !== ( $GLOBALS['pagenow'] ?? '' ) ) {
			return false;
		}

		// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- Read-only routing check; no form data is processed.
		return isset( $_GET['page'] ) && static::MENU_SLUG === sanitize_text_field( wp_unslash( $_GET['page'] ) );
	}

	/**
	 * Register the page, unless something else already serves the slug.
	 *
	 * @return void
	 */
	public static function register_page() {
		// A second entry under a slug someone else owns would leave two.
		if ( static::slug_is_claimed() ) {
			return;
		}

		self::$owns_page = true;

		// build/build.php defines the render callback but only loads on this page's
		// own request; elsewhere the callback never runs, so any callable will do.
		$callback = function_exists( static::RENDER_CALLBACK )
			? static::RENDER_CALLBACK
			: '__return_empty_string';

		$hook = add_submenu_page(
			'jetpack',
			esc_attr__( 'Monetize', 'jetpack-mu-wpcom' ),
			__( 'Monetize', 'jetpack-mu-wpcom' ),
			'manage_options',
			static::MENU_SLUG,
			$callback
		);

		self::$screen_id = $hook ? $hook : null;
	}

	/**
	 * Whether this page registered its slug on this request.
	 *
	 * @return bool
	 */
	public static function owns_page() {
		return self::$owns_page;
	}

	/**
	 * Reset the registration state. Test seam; production sets this once per request.
	 *
	 * @return void
	 */
	public static function reset() {
		self::$owns_page           = false;
		self::$screen_id           = null;
		self::$displaced_screen_id = null;
	}

	/**
	 * Whether something has already registered this page's slug.
	 *
	 * @return bool
	 */
	public static function slug_is_claimed() {
		global $submenu;

		if ( empty( $submenu['jetpack'] ) || ! is_array( $submenu['jetpack'] ) ) {
			return false;
		}

		foreach ( $submenu['jetpack'] as $item ) {
			if ( is_array( $item ) && isset( $item[2] ) && static::MENU_SLUG === $item[2] ) {
				return true;
			}
		}

		return false;
	}

	/**
	 * Load the wp-build generated asset registrations and the boot polyfills.
	 *
	 * @return void
	 */
	public static function load_wp_build() {
		$wp_build_index = static::build_dir() . '/build.php';
		require_once $wp_build_index;

		// Register polyfills for WP < 7.0 (must run before enqueue).
		WP_Build_Polyfills::register(
			'jetpack-mu-wpcom',
			array_merge(
				WP_Build_Polyfills::SCRIPT_HANDLES,
				WP_Build_Polyfills::MODULE_IDS
			)
		);
	}

	/**
	 * Make wp-build's enqueue check pass without changing the page URL.
	 *
	 * Paired with restore_screen_id() so the rewritten ID never outlives the enqueue pass.
	 *
	 * @return void
	 */
	public static function alias_screen_id() {
		$screen = get_current_screen();

		if ( ! static::owns_page() || ! is_object( $screen ) ) {
			return;
		}

		self::$displaced_screen_id = $screen->id;
		$screen->id                = static::WP_BUILD_PAGE;
	}

	/**
	 * Put back the screen ID displaced by alias_screen_id().
	 *
	 * @return void
	 */
	public static function restore_screen_id() {
		$screen = get_current_screen();

		if ( null === self::$displaced_screen_id || ! is_object( $screen ) ) {
			return;
		}

		$screen->id                = self::$displaced_screen_id;
		self::$displaced_screen_id = null;
	}

	/**
	 * The site facts every section reads, so none of them has to fetch the site, its plan or its features.
	 *
	 * @return array
	 */
	public static function get_initial_state() {
		$features = array();
		foreach ( self::FEATURES as $key => $feature ) {
			$features[ $key ] = function_exists( 'wpcom_site_has_feature' ) && (bool) wpcom_site_has_feature( $feature );
		}

		return array(
			'domain'         => (string) wp_parse_url( home_url(), PHP_URL_HOST ),
			'blogId'         => (int) get_wpcom_blog_id(),
			'siteUrl'        => home_url(),
			'isAtomic'       => Constants::is_true( 'IS_ATOMIC' ),
			'features'       => $features,
			'wordadsEnabled' => wpcom_premium_analytics_wordads_is_enabled(),
			'siteIntent'     => (string) get_option( 'site_intent', '' ),
		);
	}

	/**
	 * Hand the initial state to the page's boot script.
	 *
	 * Printed as JSON rather than through wp_localize_script(), which turns booleans into strings.
	 *
	 * @return void
	 */
	public static function enqueue_initial_state() {
		$handle = static::WP_BUILD_PAGE . '-wp-admin-prerequisites';

		if ( ! static::owns_page() || ! wp_script_is( $handle, 'registered' ) || ! current_user_can( 'manage_options' ) ) {
			return;
		}

		Common\wpcom_enqueue_tracking_scripts( $handle );

		wp_add_inline_script(
			$handle,
			'window.' . self::INITIAL_STATE_VAR . ' = ' . wp_json_encode( static::get_initial_state(), JSON_HEX_TAG | JSON_HEX_AMP | JSON_UNESCAPED_SLASHES ) . ';',
			'before'
		);
	}

	/**
	 * Install the JS translation catalogs on the prerequisites script, which runs before the boot
	 * module, so every `__()` in the route bundles evaluates translated.
	 *
	 * @return void
	 */
	public static function enqueue_script_translations() {
		$handle    = static::WP_BUILD_PAGE . '-wp-admin-prerequisites';
		$build_dir = static::build_dir();
		$constants = $build_dir . '/constants.php';

		if ( ! static::owns_page() || ! wp_script_is( $handle, 'registered' ) || ! file_exists( $constants ) ) {
			return;
		}

		$build_constants = require $constants;
		$translations    = wpcom_wp_build_script_translations( $build_dir . '/i18n-manifest.json', $build_constants['build_url'], static::get_routes() );

		if ( null !== $translations ) {
			wp_add_inline_script( $handle, $translations, 'before' );
		}
	}

	/**
	 * Keep JITMs off the page, which has no `#jp-admin-notices` to show them in.
	 *
	 * Fetching a JITM records a view, so one the page hides would still be counted.
	 *
	 * @param bool   $show      Whether to show JITMs on the screen.
	 * @param string $screen_id The screen ID.
	 * @return bool
	 */
	public static function hide_jitms( $show, $screen_id ) {
		return null !== self::$screen_id && self::$screen_id === $screen_id ? false : $show;
	}
}

WPCOM_Earn::register_feature_flag();
add_action( 'init', array( WPCOM_Earn::class, 'init' ) );
